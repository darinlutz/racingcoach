// What multi-simulator support adds to the database, run by ensureUserSchema (users.ts) once "Tracks", "Cars" and
// "CollectorLaps" exist. Only adds: existing rows keep every value and count as iRacing's, which they are, and
// ADD COLUMN with a constant default doesn't rewrite the table. See docs/multi-simulator.md.
export const SIMULATOR_SCHEMA = [
  // Which simulator a lap is from, and the format of its details. track_key is the site's track, which for iRacing is
  // iRacing's own key; native_track_key is another simulator's own id for it (NULL for iRacing, as track_key has it)
  `ALTER TABLE racingcoach."CollectorLaps" ADD COLUMN IF NOT EXISTS simulator TEXT NOT NULL DEFAULT 'iracing'`,
  `ALTER TABLE racingcoach."CollectorLaps" ADD COLUMN IF NOT EXISTS native_track_key TEXT`,
  `ALTER TABLE racingcoach."CollectorLaps" ADD COLUMN IF NOT EXISTS payload_version INTEGER NOT NULL DEFAULT 1`,
  `ALTER TABLE racingcoach."CollectorLaps" ADD COLUMN IF NOT EXISTS adapter_version TEXT`,
  // Other simulators' tracks and cars, each mapped to one of the site's only on purpose (simulatorMappings.ts)
  `CREATE TABLE IF NOT EXISTS racingcoach."SimulatorTracks" (
     id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
     simulator TEXT NOT NULL,
     native_key TEXT NOT NULL,
     native_name TEXT NOT NULL,
     track_id INTEGER REFERENCES racingcoach."Tracks"(id) ON DELETE SET NULL,
     mapped_at TIMESTAMPTZ,
     first_seen_at TIMESTAMPTZ NOT NULL DEFAULT now(),
     last_seen_at TIMESTAMPTZ NOT NULL DEFAULT now()
   )`,
  `CREATE UNIQUE INDEX IF NOT EXISTS simulator_tracks_native_key ON racingcoach."SimulatorTracks" (simulator, lower(native_key))`,
  `CREATE TABLE IF NOT EXISTS racingcoach."SimulatorCars" (
     id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
     simulator TEXT NOT NULL,
     native_key TEXT NOT NULL,
     native_name TEXT NOT NULL,
     car_id INTEGER REFERENCES racingcoach."Cars"(id) ON DELETE SET NULL,
     mapped_at TIMESTAMPTZ,
     first_seen_at TIMESTAMPTZ NOT NULL DEFAULT now(),
     last_seen_at TIMESTAMPTZ NOT NULL DEFAULT now()
   )`,
  `CREATE UNIQUE INDEX IF NOT EXISTS simulator_cars_native_key ON racingcoach."SimulatorCars" (simulator, lower(native_key))`,
];
