// Fills racingcoach."TracksNumberOfCorners" with TRACK_CORNERS, on the caller's transaction. Runs once,
// when the table is first created or gets its track_id column; a layout already there gets its track_id
// and nothing else changes.
export async function seedTrackCorners(client: PoolClient): Promise<void> {
  const column = <K extends keyof TrackCorners>(key: K) => TRACK_CORNERS.map((t) => t[key]);
  await client.query(
    `INSERT INTO racingcoach."TracksNumberOfCorners" (track_id, track_name, config_name, number_of_corners)
     SELECT * FROM unnest($1::int[], $2::text[], $3::text[], $4::int[])
     ON CONFLICT (lower(track_name), lower(config_name)) DO UPDATE SET track_id = EXCLUDED.track_id`,
    [column('trackId'), column('track'), column('config'), column('corners')]
  );
}
