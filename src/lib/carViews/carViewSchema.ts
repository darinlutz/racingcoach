// The engineering car drawings' tables (docs/car-views.md), run by ensureUserSchema (users.ts) once "Cars" and
// "Users" exist. Additive only: new tables and indexes, nothing existing is changed.
//
// The drawings themselves are small sanitized SVG markup (svgSanitize.ts), kept in the row's views JSONB, not in
// object storage. A version belongs to a Car Data car, deleted with it; the Admins who uploaded, reviewed or
// activated it are kept as ids, set NULL when their account is deleted (the privacy inventory's uploadsAsCoach).
export const CAR_VIEW_SCHEMA = [
  `CREATE TABLE IF NOT EXISTS racingcoach."CarEngineeringAssets" (
     id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
     car_id INTEGER NOT NULL REFERENCES racingcoach."Cars"(id) ON DELETE CASCADE,
     version INTEGER NOT NULL,
     status TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'under_review', 'approved', 'rejected')),
     active BOOLEAN NOT NULL DEFAULT false,
     car_keys TEXT[] NOT NULL,
     views JSONB NOT NULL,
     sources TEXT NOT NULL DEFAULT '',
     license TEXT NOT NULL DEFAULT '',
     notes TEXT NOT NULL DEFAULT '',
     created_by INTEGER REFERENCES racingcoach."Users"(id) ON DELETE SET NULL,
     reviewed_by INTEGER REFERENCES racingcoach."Users"(id) ON DELETE SET NULL,
     activated_by INTEGER REFERENCES racingcoach."Users"(id) ON DELETE SET NULL,
     created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
     reviewed_at TIMESTAMPTZ,
     activated_at TIMESTAMPTZ,
     UNIQUE (car_id, version),
     CONSTRAINT car_engineering_assets_active_approved CHECK (NOT active OR status = 'approved')
   )`,
  // One active version per car
  `CREATE UNIQUE INDEX IF NOT EXISTS car_engineering_assets_active_idx ON racingcoach."CarEngineeringAssets" (car_id) WHERE active`,
  `CREATE INDEX IF NOT EXISTS car_engineering_assets_keys_idx ON racingcoach."CarEngineeringAssets" USING GIN (car_keys)`,
  // The other Car Data cars that use the same drawings (assetRules.ts' sharedCarIds): car_id is the car the version was
  // made for and is numbered under, and these share it. Ids rather than a foreign key, so a deleted car is simply left
  // out wherever they're read (always joined to "Cars")
  `ALTER TABLE racingcoach."CarEngineeringAssets" ADD COLUMN IF NOT EXISTS shared_car_ids INTEGER[] NOT NULL DEFAULT '{}'`,
  // Each version's review history: every action, by whom
  `CREATE TABLE IF NOT EXISTS racingcoach."CarEngineeringAssetEvents" (
     id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
     asset_id INTEGER NOT NULL REFERENCES racingcoach."CarEngineeringAssets"(id) ON DELETE CASCADE,
     action TEXT NOT NULL,
     from_status TEXT,
     to_status TEXT,
     user_id INTEGER REFERENCES racingcoach."Users"(id) ON DELETE SET NULL,
     created_at TIMESTAMPTZ NOT NULL DEFAULT now()
   )`,
  `CREATE INDEX IF NOT EXISTS car_engineering_asset_events_asset_idx ON racingcoach."CarEngineeringAssetEvents" (asset_id, created_at)`,

  // The 3D car models (docs/car-models.md, src/lib/carModels/): the same system's GLB versions, one table beside the
  // drawings' as a model is a file in object storage with its own normalization rather than SVG views. The file is never
  // in Postgres: storage_key is its object (car-models/{carId}/{sha256}.glb), sha256 its contents, so a
  // replaced model is always a new version and an approved one never changes under drivers
  `CREATE TABLE IF NOT EXISTS racingcoach."CarModelAssets" (
     id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
     car_id INTEGER NOT NULL REFERENCES racingcoach."Cars"(id) ON DELETE CASCADE,
     version INTEGER NOT NULL,
     status TEXT NOT NULL DEFAULT 'uploaded' CHECK (status IN ('uploaded', 'ready_for_review', 'approved', 'rejected')),
     active BOOLEAN NOT NULL DEFAULT false,
     car_keys TEXT[] NOT NULL,
     format TEXT NOT NULL DEFAULT 'glb' CHECK (format = 'glb'),
     storage_key TEXT NOT NULL UNIQUE,
     file_name TEXT NOT NULL DEFAULT '',
     bytes INTEGER NOT NULL CHECK (bytes > 0),
     sha256 TEXT NOT NULL CHECK (sha256 ~ '^[0-9a-f]{64}$'),
     raw_bounds JSONB NOT NULL,
     stats JSONB NOT NULL,
     warnings JSONB NOT NULL DEFAULT '[]',
     normalization JSONB NOT NULL,
     wheel_anchors JSONB NOT NULL,
     default_view TEXT NOT NULL DEFAULT 'frontThreeQuarter',
     source TEXT NOT NULL DEFAULT '',
     license TEXT NOT NULL DEFAULT '',
     attribution TEXT NOT NULL DEFAULT '',
     notes TEXT NOT NULL DEFAULT '',
     created_by INTEGER REFERENCES racingcoach."Users"(id) ON DELETE SET NULL,
     reviewed_by INTEGER REFERENCES racingcoach."Users"(id) ON DELETE SET NULL,
     activated_by INTEGER REFERENCES racingcoach."Users"(id) ON DELETE SET NULL,
     created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
     updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
     reviewed_at TIMESTAMPTZ,
     activated_at TIMESTAMPTZ,
     UNIQUE (car_id, version),
     CONSTRAINT car_model_assets_active_approved CHECK (NOT active OR status = 'approved')
   )`,
  `CREATE UNIQUE INDEX IF NOT EXISTS car_model_assets_active_idx ON racingcoach."CarModelAssets" (car_id) WHERE active`,
  `CREATE INDEX IF NOT EXISTS car_model_assets_keys_idx ON racingcoach."CarModelAssets" USING GIN (car_keys)`,
  // The other Car Data cars that use the same model, like the drawings' shared_car_ids
  `ALTER TABLE racingcoach."CarModelAssets" ADD COLUMN IF NOT EXISTS shared_car_ids INTEGER[] NOT NULL DEFAULT '{}'`,
  `CREATE TABLE IF NOT EXISTS racingcoach."CarModelAssetEvents" (
     id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
     asset_id INTEGER NOT NULL REFERENCES racingcoach."CarModelAssets"(id) ON DELETE CASCADE,
     action TEXT NOT NULL,
     from_status TEXT,
     to_status TEXT,
     user_id INTEGER REFERENCES racingcoach."Users"(id) ON DELETE SET NULL,
     created_at TIMESTAMPTZ NOT NULL DEFAULT now()
   )`,
  `CREATE INDEX IF NOT EXISTS car_model_asset_events_asset_idx ON racingcoach."CarModelAssetEvents" (asset_id, created_at)`,
];
