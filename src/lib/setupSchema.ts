// The Setups page's tables (docs/setups.md), run by ensureUserSchema (users.ts) once "Users" exists. Additive only:
// new tables and indexes, nothing existing is changed, so it's safe on the live database. Every table is tied to its
// user with ON DELETE CASCADE, so Delete Account removes it, and none is touched by the lap retention job: setups are
// kept until the user deletes them (Request Data Deletion's setups category, dataErasure.ts).
export const SETUP_SCHEMA = [
  // One setup: an uploaded .sto (kept byte for byte), or a setup the collector saw iRacing load (source sdk), or one
  // made on the Setups page (generated: a copy or the Setup Engineer's changes). Its values are in its revisions
  `CREATE TABLE IF NOT EXISTS racingcoach."Setups" (
     id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
     user_id INTEGER NOT NULL REFERENCES racingcoach."Users"(id) ON DELETE CASCADE,
     simulator TEXT NOT NULL DEFAULT 'iracing',
     name TEXT NOT NULL,
     car TEXT,
     car_key TEXT,
     track TEXT,
     track_key TEXT,
     source TEXT NOT NULL,
     file_name TEXT,
     notes TEXT NOT NULL DEFAULT '',
     sto_file BYTEA,
     sto_sha256 TEXT,
     sto_bytes INTEGER,
     sto_info JSONB,
     parse_status TEXT NOT NULL,
     parser_version INTEGER NOT NULL,
     archived_at TIMESTAMPTZ,
     created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
     updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
     CONSTRAINT setups_source_check CHECK (source IN ('sdk', 'sto', 'generated', 'imported')),
     CONSTRAINT setups_parse_status_check CHECK (parse_status IN ('decoded', 'partial', 'unsupported', 'failed', 'none'))
   )`,
  `CREATE INDEX IF NOT EXISTS setups_user ON racingcoach."Setups" (user_id, updated_at DESC)`,
  `CREATE INDEX IF NOT EXISTS setups_user_file ON racingcoach."Setups" (user_id, lower(file_name))`,
  // Each version of a setup's values, never changed once made (only a capture's readings are refreshed, see
  // setups.ts's recordCapture). kind: capture (the collector saw it in iRacing), import, manual, engineer (approved
  // Setup Engineer changes), restore, duplicate. settings_sha256 is the adjustable values' hash, for finding the same
  // setup loaded in iRacing again
  `CREATE TABLE IF NOT EXISTS racingcoach."SetupRevisions" (
     id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
     setup_id INTEGER NOT NULL REFERENCES racingcoach."Setups"(id) ON DELETE CASCADE,
     user_id INTEGER NOT NULL REFERENCES racingcoach."Users"(id) ON DELETE CASCADE,
     revision_number INTEGER NOT NULL,
     parent_revision_id INTEGER REFERENCES racingcoach."SetupRevisions"(id) ON DELETE SET NULL,
     kind TEXT NOT NULL,
     author TEXT NOT NULL,
     change_summary TEXT NOT NULL DEFAULT '',
     changed JSONB NOT NULL DEFAULT '[]',
     yaml TEXT,
     settings_sha256 TEXT,
     update_count INTEGER,
     sim_setup_name TEXT,
     sim_load_type TEXT,
     sim_modified BOOLEAN,
     fixed_session BOOLEAN,
     session_id INTEGER,
     subsession_id INTEGER,
     captured_at TIMESTAMPTZ,
     last_seen_at TIMESTAMPTZ,
     change_sheet_at TIMESTAMPTZ,
     validation TEXT NOT NULL DEFAULT 'none',
     created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
     CONSTRAINT setup_revisions_kind_check CHECK (kind IN ('capture', 'import', 'manual', 'engineer', 'restore', 'duplicate')),
     CONSTRAINT setup_revisions_author_check CHECK (author IN ('collector', 'user', 'setupEngineer')),
     CONSTRAINT setup_revisions_validation_check CHECK (validation IN ('none', 'observed')),
     UNIQUE (setup_id, revision_number)
   )`,
  `CREATE INDEX IF NOT EXISTS setup_revisions_settings ON racingcoach."SetupRevisions" (user_id, settings_sha256)`,
  // A revision's values, one row per parameter (setupYaml.ts), so they can be searched and compared in SQL
  `CREATE TABLE IF NOT EXISTS racingcoach."SetupValues" (
     revision_id INTEGER NOT NULL REFERENCES racingcoach."SetupRevisions"(id) ON DELETE CASCADE,
     user_id INTEGER NOT NULL REFERENCES racingcoach."Users"(id) ON DELETE CASCADE,
     path TEXT NOT NULL,
     section TEXT NOT NULL,
     grp TEXT,
     key TEXT NOT NULL,
     category TEXT NOT NULL,
     raw TEXT NOT NULL,
     value DOUBLE PRECISION,
     unit TEXT,
     value_list DOUBLE PRECISION[] NOT NULL DEFAULT '{}',
     decimals INTEGER NOT NULL DEFAULT 0,
     kind TEXT NOT NULL,
     in_car BOOLEAN NOT NULL DEFAULT false,
     ord INTEGER NOT NULL,
     PRIMARY KEY (revision_id, path)
   )`,
  // iRacing's inspection result (DriverSetupPassedTech) each time a capture saw it change, with where; revision_id is
  // the revision whose adjustable values iRacing had loaded, when they match one exactly
  `CREATE TABLE IF NOT EXISTS racingcoach."SetupInspections" (
     id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
     user_id INTEGER NOT NULL REFERENCES racingcoach."Users"(id) ON DELETE CASCADE,
     setup_id INTEGER REFERENCES racingcoach."Setups"(id) ON DELETE CASCADE,
     revision_id INTEGER REFERENCES racingcoach."SetupRevisions"(id) ON DELETE SET NULL,
     matched_revision_id INTEGER REFERENCES racingcoach."SetupRevisions"(id) ON DELETE SET NULL,
     result TEXT NOT NULL,
     passed_tech INTEGER,
     sim_setup_name TEXT,
     car TEXT,
     track TEXT,
     session_id INTEGER,
     subsession_id INTEGER,
     observed_at TIMESTAMPTZ NOT NULL,
     last_observed_at TIMESTAMPTZ NOT NULL,
     CONSTRAINT setup_inspections_result_check CHECK (result IN ('passed', 'failed', 'unknown'))
   )`,
  `CREATE INDEX IF NOT EXISTS setup_inspections_user ON racingcoach."SetupInspections" (user_id, last_observed_at DESC)`,
  // The Setup Engineer's analyses on the Setups page: the question, its answer and the changes it proposed, each
  // pending until the driver accepts or rejects it; resulting_revision_id is the revision the accepted ones made
  `CREATE TABLE IF NOT EXISTS racingcoach."SetupProposals" (
     id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
     user_id INTEGER NOT NULL REFERENCES racingcoach."Users"(id) ON DELETE CASCADE,
     setup_id INTEGER NOT NULL REFERENCES racingcoach."Setups"(id) ON DELETE CASCADE,
     revision_id INTEGER REFERENCES racingcoach."SetupRevisions"(id) ON DELETE SET NULL,
     compare_revision_id INTEGER REFERENCES racingcoach."SetupRevisions"(id) ON DELETE SET NULL,
     question TEXT NOT NULL,
     answer JSONB NOT NULL,
     changes JSONB NOT NULL DEFAULT '[]',
     resulting_revision_id INTEGER REFERENCES racingcoach."SetupRevisions"(id) ON DELETE SET NULL,
     created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
     decided_at TIMESTAMPTZ
   )`,
  `CREATE INDEX IF NOT EXISTS setup_proposals_user ON racingcoach."SetupProposals" (user_id, created_at DESC)`,
];

export const SETUP_TABLES = ['Setups', 'SetupRevisions', 'SetupValues', 'SetupInspections', 'SetupProposals'];
