import { query } from './db';
import { DEFAULT_LIVE_VIDEO_SETTINGS, parseLiveVideoSettings, type LiveVideoSettings } from './liveVideo/broadcastSource';
import { MAX_LIVE_STREAMS } from './liveVideo/streamRules';
import { ensureUserSchema } from './users';

// Live video's table (docs/live-video.md), created on first use:
//   "LiveVideoStreams"       the Cloudflare live inputs an Admin added, each tied to the driver account whose racing it
//                            shows (deleted with that account). Never a stream key or token: those stay in Cloudflare
// "BroadcastSourceStates" (each race session's camera, from when TVs switched between the map and OBS) is dropped.
// The settings are in "SiteSettings", key live_video. Telemetry samples are never stored: the synchronization buffer
// lives in each viewer's browser.

export const LIVE_VIDEO_SCHEMA: string[] = [
  `CREATE TABLE IF NOT EXISTS racingcoach."LiveVideoStreams" (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES racingcoach."Users"(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    input_id TEXT NOT NULL UNIQUE CHECK (input_id ~ '^[a-f0-9]{32}$'),
    -- The input requires signed URLs in Cloudflare, so viewers get a signed token instead of the input ID
    require_signed BOOLEAN NOT NULL DEFAULT false,
    enabled BOOLEAN NOT NULL DEFAULT true,
    -- created through the API by the Admin page, or an input made in the Cloudflare dashboard and registered
    created_via TEXT NOT NULL DEFAULT 'registered' CHECK (created_via IN ('api', 'registered')),
    created_by INTEGER REFERENCES racingcoach."Users"(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
  )`,
  // One stream per driver: the one their broadcast shows
  'CREATE UNIQUE INDEX IF NOT EXISTS live_video_streams_user_idx ON racingcoach."LiveVideoStreams" (user_id)',
  'DROP TABLE IF EXISTS racingcoach."BroadcastSourceStates"',
];

const LIVE_VIDEO_KEY = 'live_video';

let ready: Promise<void> | null = null;
export function ensureLiveVideoSchema(): Promise<void> {
  ready ??= (async () => {
    await ensureUserSchema();
    for (const statement of LIVE_VIDEO_SCHEMA) await query(statement);
  })().catch((error) => {
    ready = null;
    throw error;
  });
  return ready;
}

export type LiveStream = {
  id: number;
  userId: number;
  userName: string;
  name: string;
  inputId: string;
  requireSigned: boolean;
  enabled: boolean;
  createdVia: 'api' | 'registered';
  createdAt: string;
};

type StreamRow = {
  id: number;
  user_id: number;
  user_name: string;
  name: string;
  input_id: string;
  require_signed: boolean;
  enabled: boolean;
  created_via: 'api' | 'registered';
  created_at: Date;
};

const toStream = (r: StreamRow): LiveStream => ({
  id: r.id,
  userId: r.user_id,
  userName: r.user_name,
  name: r.name,
  inputId: r.input_id,
  requireSigned: r.require_signed,
  enabled: r.enabled,
  createdVia: r.created_via,
  createdAt: r.created_at.toISOString(),
});

const SELECT = `SELECT s.id, s.user_id, u.user_name, s.name, s.input_id, s.require_signed, s.enabled, s.created_via, s.created_at
  FROM racingcoach."LiveVideoStreams" s JOIN racingcoach."Users" u ON u.id = s.user_id`;

export async function listStreams(): Promise<LiveStream[]> {
  await ensureLiveVideoSchema();
  return (await query<StreamRow>(`${SELECT} ORDER BY s.created_at`)).map(toStream);
}

// The streams of these drivers that are switched on, by driver; read often, so cached briefly
let streamsCache: { at: number; streams: LiveStream[] } | null = null;
const STREAMS_CACHE_MS = 15_000;
export async function enabledStreams(): Promise<LiveStream[]> {
  if (streamsCache && Date.now() - streamsCache.at < STREAMS_CACHE_MS) return streamsCache.streams;
  const streams = (await listStreams()).filter((s) => s.enabled);
  streamsCache = { at: Date.now(), streams };
  return streams;
}
const forgetStreams = () => {
  streamsCache = null;
};

export class StreamLimitError extends Error {}

export async function addStream(input: { userId: number; name: string; inputId: string; requireSigned: boolean; createdVia: 'api' | 'registered'; createdBy: number }): Promise<LiveStream> {
  await ensureLiveVideoSchema();
  const [{ count }] = await query<{ count: string }>('SELECT count(*) FROM racingcoach."LiveVideoStreams"');
  if (Number(count) >= MAX_LIVE_STREAMS) throw new StreamLimitError(`At most ${MAX_LIVE_STREAMS} live streams`);
  const [row] = await query<{ id: number }>(
    `INSERT INTO racingcoach."LiveVideoStreams" (user_id, name, input_id, require_signed, created_via, created_by)
     VALUES ($1, $2, $3, $4, $5, $6) RETURNING id`,
    [input.userId, input.name, input.inputId, input.requireSigned, input.createdVia, input.createdBy]
  );
  forgetStreams();
  const [stream] = await query<StreamRow>(`${SELECT} WHERE s.id = $1`, [row.id]);
  return toStream(stream);
}

export async function readStream(id: number): Promise<LiveStream | null> {
  await ensureLiveVideoSchema();
  const [row] = await query<StreamRow>(`${SELECT} WHERE s.id = $1`, [id]);
  return row ? toStream(row) : null;
}

export async function updateStream(id: number, changes: { enabled?: boolean; requireSigned?: boolean; name?: string }): Promise<LiveStream | null> {
  await ensureLiveVideoSchema();
  await query(
    `UPDATE racingcoach."LiveVideoStreams" SET enabled = COALESCE($2, enabled), require_signed = COALESCE($3, require_signed),
       name = COALESCE($4, name), updated_at = now() WHERE id = $1`,
    [id, changes.enabled ?? null, changes.requireSigned ?? null, changes.name ?? null]
  );
  forgetStreams();
  return readStream(id);
}

export async function removeStream(id: number): Promise<LiveStream | null> {
  const stream = await readStream(id);
  if (!stream) return null;
  await query('DELETE FROM racingcoach."LiveVideoStreams" WHERE id = $1', [id]);
  forgetStreams();
  return stream;
}

// The settings; cached a few seconds, as every TV picture reads them
let settingsCache: { at: number; settings: LiveVideoSettings } | null = null;
const SETTINGS_CACHE_MS = 5000;

export async function getLiveVideoSettings(fresh = false): Promise<LiveVideoSettings> {
  if (!fresh && settingsCache && Date.now() - settingsCache.at < SETTINGS_CACHE_MS) return settingsCache.settings;
  await ensureUserSchema();
  const [row] = await query<{ value: string }>('SELECT value FROM racingcoach."SiteSettings" WHERE key = $1', [LIVE_VIDEO_KEY]);
  let settings = DEFAULT_LIVE_VIDEO_SETTINGS;
  if (row) {
    try {
      settings = parseLiveVideoSettings(JSON.parse(row.value));
    } catch {
      // a broken row: the defaults, which have the feature off
    }
  }
  settingsCache = { at: Date.now(), settings };
  return settings;
}

export async function setLiveVideoSettings(changes: unknown, userId: number): Promise<LiveVideoSettings> {
  const current = await getLiveVideoSettings(true);
  const merged = changes && typeof changes === 'object' ? (changes as Record<string, unknown>) : {};
  const next = parseLiveVideoSettings(
    {
      ...current,
      ...merged,
      sync: { ...current.sync, ...((merged.sync as object) ?? {}) },
    },
    current
  );
  await query(
    `INSERT INTO racingcoach."SiteSettings" (key, value, updated_by) VALUES ($1, $2, $3)
     ON CONFLICT (key) DO UPDATE SET value = EXCLUDED.value, updated_at = now(), updated_by = EXCLUDED.updated_by`,
    [LIVE_VIDEO_KEY, JSON.stringify(next), userId]
  );
  settingsCache = { at: Date.now(), settings: next };
  return next;
}
