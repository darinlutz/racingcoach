// The ElevenLabs voices (the Admin page's Eleven Labs Voice Management, rules in elevenLabsVoiceRules.ts), in
// racingcoach."ElevenLabsVoices" rather than the environment. The table is created on first use; the first time, the
// voices set in the old ELEVENLABS_<LANGUAGE>_<ROLE>_VOICE_ID and ELEVENLABS_MY_VOICE_ID variables are imported into
// it (marked in "SiteSettings", so a voice the Admin deletes doesn't come back), after which those variables aren't read.
//
// Speech looks voices up on every line, synchronously (elevenLabs.ts' elevenLabsVoiceId), so each server keeps the
// enabled voices in memory: loaded at the first use, again when older than 30 s (other servers' changes reach it within
// that), and at once after an Admin change on this server. getCoachVoice, getRaceAnnouncerSettings, synthesizeSpeech
// and radioVoiceId wait for it (loadElevenLabsVoices), so a server that just started speaks with the table's voices.

export type ElevenLabsVoice = {
  id: number;
  name: string;
  voiceId: string;
  role: ElevenLabsVoiceRole;
  language: ElevenLabsVoiceLanguage;
  enabled: boolean;
  notes: string;
  // The voice's name in the ElevenLabs account, when the Voice ID was checked with ElevenLabs on saving
  elevenLabsName: string | null;
  createdAt: string;
  updatedAt: string;
};

export class ElevenLabsVoiceError extends Error {
  constructor(readonly code: 'notFound' | 'slotTaken' | 'voiceNotFound') {
    super(code);
  }
}

const SCHEMA = [
  `CREATE TABLE IF NOT EXISTS racingcoach."ElevenLabsVoices" (
     id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
     name TEXT NOT NULL,
     voice_id TEXT NOT NULL,
     role TEXT NOT NULL CONSTRAINT elevenlabs_voices_role_check
       CHECK (role IN ('raceCoach', 'leadAnnouncer', 'colorAnnouncer', 'setupEngineer', 'raceStrategist', 'ownerRadio')),
     language TEXT NOT NULL CHECK (language IN ('en', 'pt', 'de', 'fr', 'it', 'es-latam', 'es-es', 'all')),
     enabled BOOLEAN NOT NULL DEFAULT true,
     notes TEXT NOT NULL DEFAULT '',
     elevenlabs_name TEXT,
     created_by INTEGER REFERENCES racingcoach."Users"(id) ON DELETE SET NULL,
     updated_by INTEGER REFERENCES racingcoach."Users"(id) ON DELETE SET NULL,
     created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
     updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
     CONSTRAINT elevenlabs_voices_owner_all CHECK ((role = 'ownerRadio') = (language = 'all'))
   )`,
  // A table from before the Setup Engineer and Race Strategist roles has the column's own CHECK, named by Postgres,
  // without them: replaced once by the named one above
  `DO $$ BEGIN
     IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'elevenlabs_voices_role_check'
                      AND conrelid = 'racingcoach."ElevenLabsVoices"'::regclass) THEN
       ALTER TABLE racingcoach."ElevenLabsVoices" DROP CONSTRAINT IF EXISTS "ElevenLabsVoices_role_check";
       ALTER TABLE racingcoach."ElevenLabsVoices" ADD CONSTRAINT elevenlabs_voices_role_check
         CHECK (role IN ('raceCoach', 'leadAnnouncer', 'colorAnnouncer', 'setupEngineer', 'raceStrategist', 'ownerRadio'));
     END IF;
   END $$`,
  // One enabled voice per role and language
  `CREATE UNIQUE INDEX IF NOT EXISTS elevenlabs_voices_slot_idx ON racingcoach."ElevenLabsVoices" (role, language) WHERE enabled`,
];

let ready: Promise<void> | null = null;

export function ensureElevenLabsVoiceSchema(): Promise<void> {
  ready ??= (async () => {
    await ensureUserSchema();
    await transaction(async (client) => {
      for (const statement of SCHEMA) await client.query(statement);
      const { rowCount } = await client.query(
        `INSERT INTO racingcoach."SiteSettings" (key, value) VALUES ('elevenlabs_voices_imported', 'true') ON CONFLICT (key) DO NOTHING`
      );
      if (!rowCount) return;
      const imported = voicesFromEnv(process.env);
      for (const v of imported) {
        await client.query(
          `INSERT INTO racingcoach."ElevenLabsVoices" (name, voice_id, role, language, enabled, notes)
           VALUES ($1, $2, $3, $4, true, 'Imported from the server environment')
           ON CONFLICT DO NOTHING`,
          [v.name, v.voiceId, v.role, v.language]
        );
      }
      if (imported.length) console.log(`ElevenLabs voices: ${imported.length} imported from the environment variables`);
    });
  })().catch((error) => {
    ready = null;
    throw error;
  });
  return ready;
}

// The enabled voices by slot, on globalThis so every bundle of the server shares one copy
type Cache = { at: number; slots: Map<string, string>; loading: Promise<void> | null };
const store = globalThis as typeof globalThis & { rcElevenLabsVoices?: Cache };
const cache = (): Cache => (store.rcElevenLabsVoices ??= { at: 0, slots: new Map(), loading: null });
const CACHE_TTL_MS = 30_000;

async function refresh(): Promise<void> {
  await ensureElevenLabsVoiceSchema();
  const rows = await query<{ role: ElevenLabsVoiceRole; language: ElevenLabsVoiceLanguage; voice_id: string }>(
    'SELECT role, language, voice_id FROM racingcoach."ElevenLabsVoices" WHERE enabled'
  );
  const c = cache();
  c.slots = new Map(rows.map((r) => [slotKey(r.role, r.language), r.voice_id]));
  c.at = Date.now();
}

// Brings the in-memory voices up to date (at most every 30 s); a failure keeps the last ones, logged
export function loadElevenLabsVoices(force = false): Promise<void> {
  const c = cache();
  if (!force && Date.now() - c.at < CACHE_TTL_MS) return Promise.resolve();
  c.loading ??= refresh()
    .catch((error) => console.error('ElevenLabs voices load error:', error))
    .finally(() => {
      c.loading = null;
    });
  return c.loading;
}

// The enabled voice of a slot, from memory; a stale copy is refreshed in the background for the next lookup
export function cachedVoiceId(role: ElevenLabsVoiceRole, language: ElevenLabsVoiceLanguage): string | null {
  const c = cache();
  if (Date.now() - c.at >= CACHE_TTL_MS) void loadElevenLabsVoices();
  return c.slots.get(slotKey(role, language)) ?? null;
}

type Row = {
  id: number;
  name: string;
  voice_id: string;
  role: ElevenLabsVoiceRole;
  language: ElevenLabsVoiceLanguage;
  enabled: boolean;
  notes: string;
  elevenlabs_name: string | null;
  created_at: Date;
  updated_at: Date;
};
const toVoice = (r: Row): ElevenLabsVoice => ({
  id: r.id,
  name: r.name,
  voiceId: r.voice_id,
  role: r.role,
  language: r.language,
  enabled: r.enabled,
  notes: r.notes,
  elevenLabsName: r.elevenlabs_name,
  createdAt: r.created_at.toISOString(),
  updatedAt: r.updated_at.toISOString(),
});

export async function listElevenLabsVoices(): Promise<ElevenLabsVoice[]> {
  await ensureElevenLabsVoiceSchema();
  const rows = await query<Row>(`SELECT * FROM racingcoach."ElevenLabsVoices" ORDER BY role, language, enabled DESC, lower(name)`);
  return rows.map(toVoice);
}

const isSlotTaken = (error: unknown) => (error as { code?: string; constraint?: string })?.constraint === 'elevenlabs_voices_slot_idx';

// What ElevenLabs calls the voice in the account (GET /v1/voices/{id}); voiceNotFound when it has no such voice, and
// null when it can't be asked (no API key, or ElevenLabs unreachable), so the voice is saved unchecked
export async function checkVoiceWithElevenLabs(voiceId: string): Promise<string | null> {
  const key = process.env.ELEVENLABS_API_KEY || process.env.ELEVEN_LABS_API_KEY;
  if (!key) return null;
  let response: Response;
  try {
    response = await fetch(`https://api.elevenlabs.io/v1/voices/${encodeURIComponent(voiceId)}`, {
      headers: { 'xi-api-key': key },
      signal: AbortSignal.timeout(8000),
    });
  } catch (error) {
    console.error('ElevenLabs voice check error:', error);
    return null;
  }
  if (response.status === 400 || response.status === 404) throw new ElevenLabsVoiceError('voiceNotFound');
  if (!response.ok) {
    console.error(`ElevenLabs voice check answered ${response.status}`);
    return null;
  }
  const data = (await response.json().catch(() => ({}))) as { name?: unknown };
  return typeof data.name === 'string' ? data.name.slice(0, 200) : null;
}

export async function createElevenLabsVoice(voice: VoiceInput, elevenLabsName: string | null, userId: number): Promise<ElevenLabsVoice> {
  await ensureElevenLabsVoiceSchema();
  try {
    const [row] = await query<Row>(
      `INSERT INTO racingcoach."ElevenLabsVoices" (name, voice_id, role, language, enabled, notes, elevenlabs_name, created_by, updated_by)
       VALUES ($1, $2, $3, $4, $5, $6, $7, $8, $8) RETURNING *`,
      [voice.name, voice.voiceId, voice.role, voice.language, voice.enabled, voice.notes, elevenLabsName, userId]
    );
    return toVoice(row);
  } catch (error) {
    if (isSlotTaken(error)) throw new ElevenLabsVoiceError('slotTaken');
    throw error;
  } finally {
    await loadElevenLabsVoices(true);
  }
}

export async function updateElevenLabsVoice(id: number, voice: VoiceInput, elevenLabsName: string | null, userId: number): Promise<ElevenLabsVoice> {
  await ensureElevenLabsVoiceSchema();
  try {
    const [row] = await query<Row>(
      `UPDATE racingcoach."ElevenLabsVoices" SET name = $2, voice_id = $3, role = $4, language = $5, enabled = $6, notes = $7,
         elevenlabs_name = COALESCE($8, CASE WHEN voice_id = $3 THEN elevenlabs_name END), updated_by = $9, updated_at = now()
       WHERE id = $1 RETURNING *`,
      [id, voice.name, voice.voiceId, voice.role, voice.language, voice.enabled, voice.notes, elevenLabsName, userId]
    );
    if (!row) throw new ElevenLabsVoiceError('notFound');
    return toVoice(row);
  } catch (error) {
    if (isSlotTaken(error)) throw new ElevenLabsVoiceError('slotTaken');
    throw error;
  } finally {
    await loadElevenLabsVoices(true);
  }
}

export async function deleteElevenLabsVoice(id: number): Promise<void> {
  await ensureElevenLabsVoiceSchema();
  const rows = await query('DELETE FROM racingcoach."ElevenLabsVoices" WHERE id = $1 RETURNING id', [id]);
  await loadElevenLabsVoices(true);
  if (!rows.length) throw new ElevenLabsVoiceError('notFound');
}
