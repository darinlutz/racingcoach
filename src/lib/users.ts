let schemaReady: Promise<void> | null = null;

// The racingcoach schema holds the site's accounts and everything tied to one:
// Users, Track Data's Tracks and their TrackFocusAreas (shared by every user), each user's own Friends,
// the default Cars and each user's CarsUsers, IRacePlanConnections and RaceResults (from iRacePlan and the collector), DiscordConnections, saved
// DebriefSessions, the telemetry collector's CollectorKeys, uploaded CollectorLaps, CollectorLogs and CollectorLogReviews, sign-in Sessions,
// PasswordResets links, CancellationReason feedback and the ActivityLog of page views and clicks.
export function ensureUserSchema(): Promise<void> {
  if (!schemaReady) {
    schemaReady = transaction(async (client) => {
      // Concurrent CREATE ... IF NOT EXISTS can still collide in Postgres
      // when several server instances boot at once, so serialize them.
      await client.query("SELECT pg_advisory_xact_lock(hashtext('racingcoach_user_schema'))");
      await client.query('CREATE SCHEMA IF NOT EXISTS racingcoach');
      await client.query(`CREATE TABLE IF NOT EXISTS racingcoach."Users" (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_name TEXT NOT NULL,
        email_address TEXT NOT NULL,
        password TEXT NOT NULL,
        account_status TEXT NOT NULL DEFAULT '${ACCOUNT_STATUS.unsubscribed}',
        created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
        stripe_customer_id TEXT,
        stripe_subscription_id TEXT,
        signup_date TEXT,
        subscription_end_date TEXT,
        role TEXT NOT NULL DEFAULT '${ROLES.user}'
      )`);
      // Bronze, Silver or Gold (MEMBERSHIP_LEVEL). When the column is added, accounts that already paid
      // (before there were levels) are Silver, the level that matches what they bought.
      const [{ level_missing: levelMissing }] = (
        await client.query(`SELECT NOT EXISTS (
          SELECT 1 FROM information_schema.columns
          WHERE table_schema = 'racingcoach' AND table_name = 'Users' AND column_name = 'membership_level'
        ) AS level_missing`)
      ).rows;
      if (levelMissing) {
        await client.query(
          `ALTER TABLE racingcoach."Users" ADD COLUMN membership_level TEXT NOT NULL DEFAULT '${MEMBERSHIP_LEVEL.bronze}'`
        );
        await client.query(
          `UPDATE racingcoach."Users" SET membership_level = $1
           WHERE (account_status = ANY($2) AND (subscription_end_date > $3 OR subscription_end_date IS NULL))
              OR (account_status = $4 AND subscription_end_date > $3)`,
          [
            MEMBERSHIP_LEVEL.silver,
            [ACCOUNT_STATUS.subscribed, ...LEGACY_SUBSCRIBED_STATUSES],
            new Date().toISOString(),
            ACCOUNT_STATUS.canceled,
          ]
        );
      }
      // The language the site and its AI features use for the user: en, pt or es (src/lib/i18n/languages.ts)
      await client.query(
        `ALTER TABLE racingcoach."Users" ADD COLUMN IF NOT EXISTS preferred_language TEXT NOT NULL DEFAULT '${DEFAULT_LANGUAGE}'`
      );
      // Dark Mode or Light Mode for the whole site: dark or light (src/lib/theme.ts)
      await client.query(
        `ALTER TABLE racingcoach."Users" ADD COLUMN IF NOT EXISTS theme TEXT NOT NULL DEFAULT '${DEFAULT_THEME}'`
      );
      // Preferred Units for the whole site: standard (feet, mph, °F) or metric (meters, kph, °C) (src/lib/units.ts)
      await client.query(
        `ALTER TABLE racingcoach."Users" ADD COLUMN IF NOT EXISTS units TEXT NOT NULL DEFAULT '${DEFAULT_UNITS}'`
      );
      // The user's own In-Car AI Coach Instructions from the Account page (empty for none)
      await client.query(
        `ALTER TABLE racingcoach."Users" ADD COLUMN IF NOT EXISTS in_car_coach_instructions TEXT NOT NULL DEFAULT ''`
      );
      // "Beeps before braking" in the collector's window: the telemetry collector beeps 300, 200 and 100 ft
      // before each focus area's target brakepoint and higher at it (BrakeBeeps.cs). Yes by default, which
      // adding the column also sets for every existing user.
      await client.query(`ALTER TABLE racingcoach."Users" ADD COLUMN IF NOT EXISTS brake_beeps BOOLEAN NOT NULL DEFAULT true`);
      // Their volume, the collector window's slider under it: a percentage of full volume, 65 for a new account
      // (accounts from before keep theirs)
      await client.query(
        `ALTER TABLE racingcoach."Users" ADD COLUMN IF NOT EXISTS brake_beeps_volume INTEGER NOT NULL DEFAULT ${DEFAULT_BRAKE_BEEPS_VOLUME}`
      );
      await client.query(
        `ALTER TABLE racingcoach."Users" ALTER COLUMN brake_beeps_volume SET DEFAULT ${DEFAULT_BRAKE_BEEPS_VOLUME}`
      );
      // The OpenAI voice the In-Car AI Coach speaks with (src/lib/coachVoice.ts); empty for the default one
      await client.query(`ALTER TABLE racingcoach."Users" ADD COLUMN IF NOT EXISTS coach_voice TEXT NOT NULL DEFAULT ''`);
      // Its accent for Spanish: latinAmerica or spain (src/lib/coachVoice.ts); empty for the default one
      await client.query(`ALTER TABLE racingcoach."Users" ADD COLUMN IF NOT EXISTS coach_spanish_accent TEXT NOT NULL DEFAULT ''`);
      // Email addresses are unique regardless of case
      await client.query(
        'CREATE UNIQUE INDEX IF NOT EXISTS users_email_address_key ON racingcoach."Users" (lower(email_address))'
      );
      await client.query(
        'CREATE INDEX IF NOT EXISTS users_stripe_subscription_id_idx ON racingcoach."Users" (stripe_subscription_id)'
      );
      // Monthly Subscription and Lifetime Subscription are now both Subscribed
      await client.query('UPDATE racingcoach."Users" SET account_status = $1 WHERE account_status = ANY($2)', [
        ACCOUNT_STATUS.subscribed,
        LEGACY_SUBSCRIBED_STATUSES,
      ]);
      // Each friend belongs to one user. `seq` records insertion order for listing.
      await client.query(`CREATE TABLE IF NOT EXISTS racingcoach."Friends" (
        id TEXT PRIMARY KEY,
        user_id INTEGER NOT NULL REFERENCES racingcoach."Users"(id) ON DELETE CASCADE,
        name TEXT NOT NULL,
        country TEXT NOT NULL,
        created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
        seq BIGINT GENERATED BY DEFAULT AS IDENTITY
      )`);
      await client.query('CREATE INDEX IF NOT EXISTS friends_user_id_idx ON racingcoach."Friends" (user_id, seq)');
      await client.query(`CREATE TABLE IF NOT EXISTS racingcoach."Sessions" (
        token_hash TEXT PRIMARY KEY,
        user_id INTEGER NOT NULL REFERENCES racingcoach."Users"(id) ON DELETE CASCADE,
        expires_at BIGINT NOT NULL
      )`);
      await client.query('CREATE INDEX IF NOT EXISTS sessions_user_id_idx ON racingcoach."Sessions" (user_id)');
      await client.query(`CREATE TABLE IF NOT EXISTS racingcoach."PasswordResets" (
        token_hash TEXT PRIMARY KEY,
        user_id INTEGER NOT NULL REFERENCES racingcoach."Users"(id) ON DELETE CASCADE,
        expires_at BIGINT NOT NULL
      )`);
      await client.query(
        'CREATE INDEX IF NOT EXISTS password_resets_user_id_idx ON racingcoach."PasswordResets" (user_id)'
      );
      // Users used to have their own tracks and focus areas ("UsersTracks" and "UsersFocusAreas", and
      // before that "Tracks" with a user_id and "FocusAreas"); everyone now uses Tracks and TrackFocusAreas
      await client.query('DROP TABLE IF EXISTS racingcoach."UsersFocusAreas", racingcoach."UsersTracks", racingcoach."FocusAreas"');
      const [{ tracks_has_user_id: tracksHasUserId }] = (
        await client.query(`SELECT EXISTS (
          SELECT 1 FROM information_schema.columns
          WHERE table_schema = 'racingcoach' AND table_name = 'Tracks' AND column_name = 'user_id'
        ) AS tracks_has_user_id`)
      ).rows;
      if (tracksHasUserId) await client.query('DROP TABLE racingcoach."Tracks"');
      // Track Data: the tracks (DEFAULT_TRACKS, seeded once) and their focus areas, shared by every user and
      // not tied to any. track_key is the iRacing track key (e.g. "monza full") and track_name the name
      // Garage 61 puts in its CSV file names (TrackFileName); both are unique.
      const [{ tracks_missing: tracksMissing }] = (
        await client.query(`SELECT to_regclass('racingcoach."Tracks"') IS NULL AS tracks_missing`)
      ).rows;
      // config_name and number_of_corners come from TracksNumberOfCorners (appendTrackCorners, below)
      const [{ tracks_lack_corners: tracksLackCorners }] = (
        await client.query(`SELECT NOT EXISTS (
          SELECT 1 FROM information_schema.columns
          WHERE table_schema = 'racingcoach' AND table_name = 'Tracks' AND column_name = 'config_name'
        ) AS tracks_lack_corners`)
      ).rows;
      // track_category is worked out from the names and number_of_corners (categorizeTracks, below)
      const [{ tracks_lack_category: tracksLackCategory }] = (
        await client.query(`SELECT NOT EXISTS (
          SELECT 1 FROM information_schema.columns
          WHERE table_schema = 'racingcoach' AND table_name = 'Tracks' AND column_name = 'track_category'
        ) AS tracks_lack_category`)
      ).rows;
      await client.query(`CREATE TABLE IF NOT EXISTS racingcoach."Tracks" (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        track_key TEXT NOT NULL,
        track_name TEXT NOT NULL,
        notes TEXT,
        config_name TEXT,
        number_of_corners INTEGER CHECK (number_of_corners > 0),
        track_category TEXT CHECK (track_category IN ('Dirt', 'Oval', 'Road Course')),
        created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
        updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
      )`);
      // iRacing's length of the layout (WeekendInfo.TrackLength), sent by the collector with its laps (trackLengths.ts)
      await client.query(
        'ALTER TABLE racingcoach."Tracks" ADD COLUMN IF NOT EXISTS track_length_feet DOUBLE PRECISION CHECK (track_length_feet > 0)'
      );
      await client.query('ALTER TABLE racingcoach."Tracks" ADD COLUMN IF NOT EXISTS config_name TEXT');
      await client.query(
        'ALTER TABLE racingcoach."Tracks" ADD COLUMN IF NOT EXISTS number_of_corners INTEGER CHECK (number_of_corners > 0)'
      );
      await client.query(
        `ALTER TABLE racingcoach."Tracks" ADD COLUMN IF NOT EXISTS track_category TEXT
         CHECK (track_category IN ('Dirt', 'Oval', 'Road Course'))`
      );
      await client.query(
        'CREATE UNIQUE INDEX IF NOT EXISTS tracks_track_key_key ON racingcoach."Tracks" (lower(track_key))'
      );
      await client.query(
        'CREATE UNIQUE INDEX IF NOT EXISTS tracks_track_name_key ON racingcoach."Tracks" (lower(track_name))'
      );
      // Up to 8 focus areas per track: position runs 1-8 in order around the lap and is unique per track.
      // start_point/end_point are fractions of a lap (LapDistPct). The brake and on-throttle points are feet
      // from the start/finish line and max_brake_pct is a percent; NULL means no target is set.
      await client.query(`CREATE TABLE IF NOT EXISTS racingcoach."TrackFocusAreas" (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        track_id INTEGER NOT NULL REFERENCES racingcoach."Tracks"(id) ON DELETE CASCADE,
        position SMALLINT NOT NULL CHECK (position BETWEEN 1 AND 8),
        name TEXT NOT NULL,
        start_point DOUBLE PRECISION NOT NULL CHECK (start_point >= 0 AND start_point <= 1),
        end_point DOUBLE PRECISION NOT NULL CHECK (end_point >= 0 AND end_point <= 1),
        notes TEXT,
        brake_point_feet INTEGER CHECK (brake_point_feet >= 0),
        max_brake_pct SMALLINT CHECK (max_brake_pct BETWEEN 0 AND 100),
        throttle_point_feet INTEGER CHECK (throttle_point_feet >= 0),
        CHECK (start_point < end_point),
        UNIQUE (track_id, position)
      )`);
      // The default tracks are seeded when Tracks is first created
      if (tracksMissing) await seedDefaultTracks(client);
      // The number of corners per lap of every iRacing track layout (TRACK_CORNERS, seeded once), not
      // tied to any user. track_id is the layout's name in iRacing's session info (WeekendInfo.TrackName,
      // e.g. "monza full"), NULL when not known. config_name is iRacing's layout name ("Default" for
      // single-layout tracks); track and layout together are unique, and so is track_id.
      const [{ track_id_type: trackIdType }] = (
        await client.query(
          `SELECT (SELECT data_type FROM information_schema.columns WHERE table_schema = 'racingcoach'
             AND table_name = 'TracksNumberOfCorners' AND column_name = 'track_id') AS track_id_type`
        )
      ).rows;
      await client.query(`CREATE TABLE IF NOT EXISTS racingcoach."TracksNumberOfCorners" (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        track_id TEXT,
        track_name TEXT NOT NULL,
        config_name TEXT NOT NULL,
        number_of_corners INTEGER NOT NULL CHECK (number_of_corners > 0)
      )`);
      // An older copy kept iRacing's numeric track ID here, or had no track_id at all
      await client.query('ALTER TABLE racingcoach."TracksNumberOfCorners" ADD COLUMN IF NOT EXISTS track_id TEXT');
      if (trackIdType && trackIdType !== 'text') {
        await client.query('DROP INDEX IF EXISTS racingcoach.tracks_number_of_corners_track_id_key');
        await client.query(
          'ALTER TABLE racingcoach."TracksNumberOfCorners" ALTER COLUMN track_id TYPE TEXT USING NULL'
        );
      }
      await client.query(
        'CREATE UNIQUE INDEX IF NOT EXISTS tracks_number_of_corners_track_config_key ON racingcoach."TracksNumberOfCorners" (lower(track_name), lower(config_name))'
      );
      await client.query(
        'CREATE UNIQUE INDEX IF NOT EXISTS tracks_number_of_corners_track_id_key ON racingcoach."TracksNumberOfCorners" (lower(track_id))'
      );
      // Seeded when the table is first created, or given its track IDs when an older copy lacks them
      if (trackIdType !== 'text') await seedTrackCorners(client);
      // Once, when Tracks gets its config_name and number_of_corners columns
      if (tracksLackCorners) await appendTrackCorners(client);
      // Databases that got the "[Legacy]" layouts before appendTrackCorners left them out
      await removeLegacyTracks(client);
      // Once, when Tracks gets its track_category column (after the layouts above are appended)
      if (tracksLackCategory) await categorizeTracks(client);
      // Each user's own iRacePlan API key (Settings > API Keys on iraceplan.com) and their iRacing
      // customer ID, read from iRacePlan when the key is saved
      await client.query(`CREATE TABLE IF NOT EXISTS racingcoach."IRacePlanConnections" (
        user_id INTEGER PRIMARY KEY REFERENCES racingcoach."Users"(id) ON DELETE CASCADE,
        api_key TEXT NOT NULL,
        iracing_customer_id INTEGER NOT NULL,
        iracing_name TEXT NOT NULL,
        connected_at TIMESTAMPTZ NOT NULL DEFAULT now(),
        synced_at TIMESTAMPTZ
      )`);
      // One row per race result synced from iRacePlan (one per planning) or uploaded by the telemetry
      // collector. Positions are 1-based, lap times are in seconds, and NULL means the value was not
      // reported. has_result is false for races iRacePlan has no result for this driver in, so they are
      // not fetched again.
      await client.query(`CREATE TABLE IF NOT EXISTS racingcoach."RaceResults" (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id INTEGER NOT NULL REFERENCES racingcoach."Users"(id) ON DELETE CASCADE,
        iraceplan_planning_id BIGINT NOT NULL,
        start_time TIMESTAMPTZ NOT NULL,
        series TEXT NOT NULL,
        category TEXT,
        track TEXT NOT NULL,
        car TEXT NOT NULL,
        team_race BOOLEAN NOT NULL DEFAULT false,
        has_result BOOLEAN NOT NULL DEFAULT true,
        old_irating INTEGER,
        new_irating INTEGER,
        old_safety_rating REAL,
        new_safety_rating REAL,
        start_position INTEGER,
        finish_position INTEGER,
        laps_complete INTEGER,
        laps_led INTEGER,
        incidents INTEGER,
        best_lap_seconds REAL,
        average_lap_seconds REAL,
        reason_out TEXT,
        synced_at TIMESTAMPTZ NOT NULL DEFAULT now(),
        UNIQUE (user_id, iraceplan_planning_id)
      )`);
      await client.query(
        'ALTER TABLE racingcoach."RaceResults" ADD COLUMN IF NOT EXISTS has_result BOOLEAN NOT NULL DEFAULT true'
      );
      await client.query(
        'CREATE INDEX IF NOT EXISTS race_results_user_id_start_time_idx ON racingcoach."RaceResults" (user_id, start_time)'
      );
      // Races the telemetry collector saw (source 'collector', see saveCollectorRaceResult in raceHistory.ts)
      // have no iRacePlan planning; they are keyed by iRacing's subsession and session number instead.
      // results_final is iRacing's ResultsOfficial (the result can't change any more); official_race is
      // whether the race counts for iRating and safety rating.
      await client.query('ALTER TABLE racingcoach."RaceResults" ALTER COLUMN iraceplan_planning_id DROP NOT NULL');
      await client.query(`ALTER TABLE racingcoach."RaceResults"
        ADD COLUMN IF NOT EXISTS source TEXT NOT NULL DEFAULT 'iraceplan',
        ADD COLUMN IF NOT EXISTS subsession_id BIGINT,
        ADD COLUMN IF NOT EXISTS session_num INTEGER,
        ADD COLUMN IF NOT EXISTS series_id INTEGER,
        ADD COLUMN IF NOT EXISTS iracing_customer_id INTEGER,
        ADD COLUMN IF NOT EXISTS results_final BOOLEAN,
        ADD COLUMN IF NOT EXISTS official_race BOOLEAN`);
      await client.query(
        `CREATE UNIQUE INDEX IF NOT EXISTS race_results_user_id_subsession_key
         ON racingcoach."RaceResults" (user_id, subsession_id, session_num) WHERE subsession_id IS NOT NULL`
      );
      // "CarData" used to hold each user's own cars; it becomes "CarsUsers", keeping every user's edits
      const [{ car_data_exists: carDataExists }] = (
        await client.query(`SELECT to_regclass('racingcoach."CarData"') IS NOT NULL AS car_data_exists`)
      ).rows;
      if (carDataExists) {
        await client.query('ALTER TABLE racingcoach."CarData" RENAME TO "CarsUsers"');
        await client.query('ALTER TABLE racingcoach."CarsUsers" RENAME CONSTRAINT "CarData_pkey" TO "CarsUsers_pkey"');
        await client.query(
          'ALTER TABLE racingcoach."CarsUsers" RENAME CONSTRAINT "CarData_user_id_fkey" TO "CarsUsers_user_id_fkey"'
        );
        await client.query('ALTER SEQUENCE IF EXISTS racingcoach."CarData_id_seq" RENAME TO "CarsUsers_id_seq"');
        await client.query(
          'ALTER INDEX IF EXISTS racingcoach.car_data_user_id_car_name_key RENAME TO cars_users_user_id_car_name_key'
        );
      }
      // The default cars (DEFAULT_CARS, seeded once), not tied to any user. Dimensions in inches, weights
      // in pounds (wet weight includes the driver), displacement in liters; NULL means the value is not
      // known. car_name is unique.
      const [{ cars_missing: carsMissing, cars_users_missing: carsUsersMissing }] = (
        await client.query(`SELECT to_regclass('racingcoach."Cars"') IS NULL AS cars_missing,
          to_regclass('racingcoach."CarsUsers"') IS NULL AS cars_users_missing`)
      ).rows;
      await client.query(`CREATE TABLE IF NOT EXISTS racingcoach."Cars" (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        car_name TEXT NOT NULL,
        length_in DOUBLE PRECISION CHECK (length_in > 0),
        width_in DOUBLE PRECISION CHECK (width_in > 0),
        wheelbase_in DOUBLE PRECISION CHECK (wheelbase_in > 0),
        dry_weight_lbs INTEGER CHECK (dry_weight_lbs > 0),
        wet_weight_lbs INTEGER CHECK (wet_weight_lbs > 0),
        displacement_liters DOUBLE PRECISION CHECK (displacement_liters > 0),
        rpm_limit INTEGER CHECK (rpm_limit > 0),
        torque_lb_ft INTEGER CHECK (torque_lb_ft > 0),
        power_bhp INTEGER CHECK (power_bhp > 0),
        notes TEXT,
        created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
        updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
      )`);
      await client.query('CREATE UNIQUE INDEX IF NOT EXISTS cars_car_name_key ON racingcoach."Cars" (lower(car_name))');
      // Each user's own cars, copied from Cars at sign-up and edited in the Car Data tab. Same columns as
      // Cars plus user_id; car_name is unique per user.
      await client.query(`CREATE TABLE IF NOT EXISTS racingcoach."CarsUsers" (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id INTEGER NOT NULL REFERENCES racingcoach."Users"(id) ON DELETE CASCADE,
        car_name TEXT NOT NULL,
        length_in DOUBLE PRECISION CHECK (length_in > 0),
        width_in DOUBLE PRECISION CHECK (width_in > 0),
        wheelbase_in DOUBLE PRECISION CHECK (wheelbase_in > 0),
        dry_weight_lbs INTEGER CHECK (dry_weight_lbs > 0),
        wet_weight_lbs INTEGER CHECK (wet_weight_lbs > 0),
        displacement_liters DOUBLE PRECISION CHECK (displacement_liters > 0),
        rpm_limit INTEGER CHECK (rpm_limit > 0),
        torque_lb_ft INTEGER CHECK (torque_lb_ft > 0),
        power_bhp INTEGER CHECK (power_bhp > 0),
        notes TEXT,
        created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
        updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
      )`);
      await client.query(
        'CREATE UNIQUE INDEX IF NOT EXISTS cars_users_user_id_car_name_key ON racingcoach."CarsUsers" (user_id, lower(car_name))'
      );
      // The default cars are seeded when Cars is first created. Accounts that existed before CarsUsers (or
      // CarData before it) did get their copy once, here; new accounts get theirs when they sign up (createUser)
      if (carsMissing) await seedDefaultCars(client);
      if (carsUsersMissing) await copyDefaultCars(client, null);
      // Why each monthly subscriber canceled, one row per cancellation. The user's name and email are
      // copied in so the record survives the account being deleted (user_id is then set NULL).
      // reason is one of CANCELLATION_REASONS' labels; stripe_subscription_id is the confirmation number.
      await client.query(`CREATE TABLE IF NOT EXISTS racingcoach."CancellationReason" (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id INTEGER REFERENCES racingcoach."Users"(id) ON DELETE SET NULL,
        user_name TEXT NOT NULL,
        email_address TEXT NOT NULL,
        canceled_at TIMESTAMPTZ NOT NULL,
        reason TEXT NOT NULL,
        notes TEXT,
        stripe_subscription_id TEXT NOT NULL,
        subscription_end_date TEXT
      )`);
      await client.query(
        'CREATE INDEX IF NOT EXISTS cancellation_reason_user_id_idx ON racingcoach."CancellationReason" (user_id)'
      );
      // Each user's linked Discord account (Discord OAuth2, identify scope). A Discord account can be
      // linked to only one user. No Discord tokens are kept.
      await client.query(`CREATE TABLE IF NOT EXISTS racingcoach."DiscordConnections" (
        user_id INTEGER PRIMARY KEY REFERENCES racingcoach."Users"(id) ON DELETE CASCADE,
        discord_user_id TEXT NOT NULL UNIQUE,
        discord_username TEXT NOT NULL,
        discord_global_name TEXT,
        discord_avatar TEXT,
        connected_at TIMESTAMPTZ NOT NULL DEFAULT now()
      )`);
      // Each Debrief Coach run by a signed-in user: the session the browser measured from the lap CSVs
      // (the CSVs themselves are not uploaded) and the coach's debrief, both as sent and returned by
      // /api/debrief-coach. Read back by the Discord bot's /coach debrief. best_lap_seconds is the session's
      // fastest lap.
      await client.query(`CREATE TABLE IF NOT EXISTS racingcoach."DebriefSessions" (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id INTEGER NOT NULL REFERENCES racingcoach."Users"(id) ON DELETE CASCADE,
        track TEXT NOT NULL,
        car TEXT NOT NULL,
        lap_count INTEGER NOT NULL,
        best_lap_seconds REAL NOT NULL,
        session JSONB NOT NULL,
        debrief JSONB NOT NULL,
        created_at TIMESTAMPTZ NOT NULL DEFAULT now()
      )`);
      await client.query(
        'CREATE INDEX IF NOT EXISTS debrief_sessions_user_id_created_at_idx ON racingcoach."DebriefSessions" (user_id, created_at)'
      );
      // Each user's upload key for the telemetry collector (collector/), one per user. Only a hash of
      // the key is kept; key_prefix is its first characters, shown on the Account page to tell keys apart.
      await client.query(`CREATE TABLE IF NOT EXISTS racingcoach."CollectorKeys" (
        user_id INTEGER PRIMARY KEY REFERENCES racingcoach."Users"(id) ON DELETE CASCADE,
        key_hash TEXT NOT NULL UNIQUE,
        key_prefix TEXT NOT NULL,
        created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
        last_used_at TIMESTAMPTZ
      )`);
      // One row per lap uploaded by the collector: what it wrote to the lap's session.json entry, plus the
      // lap CSV itself, gzip-compressed (csv_bytes is its uncompressed size). client_lap_id is the
      // collector's own ID for the lap, so a retried upload is recognised as a duplicate. Lap times are in
      // seconds; iracing_session_id and iracing_subsession_id are 0 for offline sessions.
      await client.query(`CREATE TABLE IF NOT EXISTS racingcoach."CollectorLaps" (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id INTEGER NOT NULL REFERENCES racingcoach."Users"(id) ON DELETE CASCADE,
        client_lap_id UUID NOT NULL,
        track TEXT NOT NULL,
        car TEXT NOT NULL,
        driver TEXT NOT NULL,
        iracing_session_id BIGINT NOT NULL,
        iracing_subsession_id BIGINT NOT NULL,
        session_num INTEGER NOT NULL,
        session_type TEXT NOT NULL,
        lap_number INTEGER NOT NULL,
        lap_time_seconds DOUBLE PRECISION NOT NULL,
        sample_count INTEGER NOT NULL,
        missing_samples INTEGER NOT NULL,
        incidents INTEGER NOT NULL,
        pit_road BOOLEAN NOT NULL,
        off_track BOOLEAN NOT NULL,
        recorded_at TIMESTAMPTZ NOT NULL,
        uploaded_at TIMESTAMPTZ NOT NULL DEFAULT now(),
        csv_bytes INTEGER NOT NULL,
        csv_gzip BYTEA NOT NULL,
        UNIQUE (user_id, client_lap_id)
      )`);
      // True when the CSV has Lat/Lon columns, which the collector adds from iRacing's .ibt file after the session
      await client.query(
        'ALTER TABLE racingcoach."CollectorLaps" ADD COLUMN IF NOT EXISTS has_position BOOLEAN NOT NULL DEFAULT false'
      );
      // iRacing's track key (WeekendInfo.TrackName), which finds the Track Data track when the names differ
      await client.query('ALTER TABLE racingcoach."CollectorLaps" ADD COLUMN IF NOT EXISTS track_key TEXT');
      // Track lengths used to be in their own table; they're iRacing's, in "Tracks".track_length_feet, now
      await dropTrackLengthsTable(client);
      await client.query(
        'CREATE INDEX IF NOT EXISTS collector_laps_user_id_recorded_at_idx ON racingcoach."CollectorLaps" (user_id, recorded_at)'
      );
      // The telemetry collector's activity log, sent as it's written (src/lib/collectorLogs.ts). A run is one start
      // of the collector; seq numbers its lines, so a batch sent twice is stored once
      await client.query(`CREATE TABLE IF NOT EXISTS racingcoach."CollectorLogs" (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id INTEGER NOT NULL REFERENCES racingcoach."Users"(id) ON DELETE CASCADE,
        run_id UUID NOT NULL,
        seq INTEGER NOT NULL,
        logged_at TIMESTAMPTZ NOT NULL,
        received_at TIMESTAMPTZ NOT NULL DEFAULT now(),
        is_error BOOLEAN NOT NULL DEFAULT false,
        message TEXT NOT NULL,
        collector_version TEXT,
        UNIQUE (user_id, run_id, seq)
      )`);
      await client.query(
        'CREATE INDEX IF NOT EXISTS collector_logs_user_id_logged_at_idx ON racingcoach."CollectorLogs" (user_id, logged_at)'
      );
      // The log review agent's verdicts on those lines (src/lib/collectorLogReview.ts): one row per review of a
      // run's new lines (from_seq to to_seq), and when a problem was emailed to the site owner
      await client.query(`CREATE TABLE IF NOT EXISTS racingcoach."CollectorLogReviews" (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id INTEGER NOT NULL REFERENCES racingcoach."Users"(id) ON DELETE CASCADE,
        run_id UUID NOT NULL,
        from_seq INTEGER NOT NULL,
        to_seq INTEGER NOT NULL,
        reviewed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
        problem BOOLEAN NOT NULL,
        title TEXT,
        explanation TEXT,
        fix TEXT,
        emailed_at TIMESTAMPTZ
      )`);
      await client.query(
        'CREATE INDEX IF NOT EXISTS collector_log_reviews_user_id_run_id_idx ON racingcoach."CollectorLogReviews" (user_id, run_id)'
      );
      // Every page view and click on the site (src/lib/activityLog.ts). user_id is null for visitors who
      // aren't signed in; visitor_id ties their rows together (and to the account they later sign up for),
      // session_id groups one browser tab's visit. occurred_at is when it happened in the browser,
      // logged_at when it reached the server (events are sent in batches).
      await client.query(`CREATE TABLE IF NOT EXISTS racingcoach."ActivityLog" (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        occurred_at TIMESTAMPTZ NOT NULL,
        logged_at TIMESTAMPTZ NOT NULL DEFAULT now(),
        user_id INTEGER REFERENCES racingcoach."Users"(id) ON DELETE CASCADE,
        visitor_id UUID NOT NULL,
        session_id UUID NOT NULL,
        event_type TEXT NOT NULL,
        path TEXT NOT NULL,
        page_title TEXT,
        referrer TEXT,
        element TEXT,
        element_id TEXT,
        label TEXT,
        target_href TEXT,
        viewport_width INTEGER,
        viewport_height INTEGER,
        language TEXT,
        ip_address TEXT,
        user_agent TEXT
      )`);
      await client.query('CREATE INDEX IF NOT EXISTS activity_log_occurred_at_idx ON racingcoach."ActivityLog" (occurred_at)');
      await client.query(
        'CREATE INDEX IF NOT EXISTS activity_log_user_id_occurred_at_idx ON racingcoach."ActivityLog" (user_id, occurred_at)'
      );
      await client.query(
        'CREATE INDEX IF NOT EXISTS activity_log_visitor_id_occurred_at_idx ON racingcoach."ActivityLog" (visitor_id, occurred_at)'
      );
      // Site-wide settings the Admin page changes (src/lib/siteSettings.ts), one row per setting
      await client.query(`CREATE TABLE IF NOT EXISTS racingcoach."SiteSettings" (
        key TEXT PRIMARY KEY,
        value TEXT NOT NULL,
        updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
        updated_by INTEGER REFERENCES racingcoach."Users"(id) ON DELETE SET NULL
      )`);
    }).catch((error) => {
      schemaReady = null;
      throw error;
    });
  }
  return schemaReady;
}

// Stored as "scrypt$<salt hex>$<hash hex>" so the format is self-describing.
async function hashPassword(password: string): Promise<string> {
  const salt = randomBytes(16);
  const hash = await scryptAsync(password, salt, KEY_LENGTH);
  return `scrypt$${salt.toString('hex')}$${hash.toString('hex')}`;
}

async function verifyPassword(password: string, stored: string): Promise<boolean> {
  const [scheme, saltHex, hashHex] = stored.split('$');
  if (scheme !== 'scrypt' || !saltHex || !hashHex) return false;
  const expected = Buffer.from(hashHex, 'hex');
  const actual = await scryptAsync(password, Buffer.from(saltHex, 'hex'), expected.length);
  return timingSafeEqual(actual, expected);
}

function rowToUser(row: Record<string, unknown>): User {
  return {
    id: Number(row.id),
    userName: row.user_name as string,
    emailAddress: row.email_address as string,
    accountStatus: row.account_status as string,
    membershipLevel: (row.membership_level as string | null) ?? MEMBERSHIP_LEVEL.bronze,
    role: row.role as string,
    preferredLanguage: isLanguage(row.preferred_language) ? row.preferred_language : DEFAULT_LANGUAGE,
    theme: isTheme(row.theme) ? row.theme : DEFAULT_THEME,
    units: isUnits(row.units) ? row.units : DEFAULT_UNITS,
    brakeBeeps: row.brake_beeps !== false,
    brakeBeepsVolume: brakeBeepsVolume(row.brake_beeps_volume),
    signupDate: (row.signup_date as string | null) ?? null,
    subscriptionEndDate: (row.subscription_end_date as string | null) ?? null,
    stripeSubscriptionId: (row.stripe_subscription_id as string | null) ?? null,
    stripeCustomerId: (row.stripe_customer_id as string | null) ?? null,
  };
}

// Everyone else starts as a User; admins change roles on the Admin page
function initialRole(emailAddress: string): string {
  return emailAddress.trim().toLowerCase() === OWNER_EMAIL ? ROLES.admin : ROLES.user;
}

export async function createUser(input: {
  userName: string;
  emailAddress: string;
  password: string;
  preferredLanguage: Language;
}): Promise<User> {
  await ensureUserSchema();
  const passwordHash = await hashPassword(input.password);
  try {
    // The account starts at the Bronze level, with its own copy of the default cars to edit in
    // the Car Data tab
    return await transaction(async (client) => {
      const { rows } = await client.query(
        `INSERT INTO racingcoach."Users"
           (user_name, email_address, password, account_status, membership_level, signup_date, role, preferred_language)
         VALUES ($1, $2, $3, $6, $8, $4, $5, $7)
         RETURNING ${USER_COLUMNS}`,
        [
          input.userName,
          input.emailAddress,
          passwordHash,
          new Date().toISOString(),
          initialRole(input.emailAddress),
          ACCOUNT_STATUS.unsubscribed,
          input.preferredLanguage,
          MEMBERSHIP_LEVEL.bronze,
        ]
      );
      const user = rowToUser(rows[0]);
      await copyDefaultCars(client, user.id);
      // New accounts start with the site owner's iRacePlan API key, so Race Trends works straight away;
      // they can change it on the Race Trends page
      await client.query(
        `INSERT INTO racingcoach."IRacePlanConnections" (user_id, api_key, iracing_customer_id, iracing_name)
         SELECT $1, c.api_key, c.iracing_customer_id, c.iracing_name
         FROM racingcoach."IRacePlanConnections" c
         JOIN racingcoach."Users" u ON u.id = c.user_id
         WHERE lower(u.email_address) = $2 AND u.id <> $1`,
        [user.id, OWNER_EMAIL]
      );
      return user;
    });
  } catch (error) {
    if (isUniqueViolation(error)) {
      throw new EmailTakenError();
    }
    throw error;
  }
}

// Returns the user only when the email exists and the password matches.
export async function authenticateUser(emailAddress: string, password: string): Promise<User | null> {
  await ensureUserSchema();
  const [row] = await query(
    `SELECT ${USER_COLUMNS}, password FROM racingcoach."Users" WHERE lower(email_address) = lower($1)`,
    [emailAddress]
  );
  if (!row) return null;
  const ok = await verifyPassword(password, row.password as string);
  return ok ? rowToUser(row) : null;
}

