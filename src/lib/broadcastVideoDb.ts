import { VIDEO_CATEGORIES } from './broadcastVideoCategories';

// The Broadcast Video Library's and Broadcast Director's tables, run by ensureUserSchema (src/lib/users.ts). The video
// files themselves are in object storage (src/lib/objectStorage.ts); the settings are in "SiteSettings", key
// broadcast_director. A video's track and car are optional, and survive that track or car being removed.
export const BROADCAST_VIDEO_SCHEMA: string[] = [
  `CREATE TABLE IF NOT EXISTS racingcoach."BroadcastVideos" (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    category TEXT NOT NULL CHECK (category IN (${VIDEO_CATEGORIES.map((c) => `'${c}'`).join(', ')})),
    track_id INTEGER REFERENCES racingcoach."Tracks"(id) ON DELETE SET NULL,
    car_id INTEGER REFERENCES racingcoach."Cars"(id) ON DELETE SET NULL,
    storage_key TEXT NOT NULL UNIQUE,
    file_name TEXT NOT NULL,
    size_bytes BIGINT,
    -- uploading (waiting for the browser), processing (being checked), transcoding, ready or failed
    status TEXT NOT NULL DEFAULT 'uploading' CHECK (status IN ('uploading', 'processing', 'transcoding', 'ready', 'failed')),
    status_detail TEXT,
    duration_seconds DOUBLE PRECISION CHECK (duration_seconds IS NULL OR duration_seconds > 0),
    duration_set_by_admin BOOLEAN NOT NULL DEFAULT false,
    clip_start_seconds DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK (clip_start_seconds >= 0),
    clip_end_seconds DOUBLE PRECISION,
    width INTEGER,
    height INTEGER,
    video_codec TEXT,
    audio_codec TEXT,
    audio_enabled BOOLEAN NOT NULL DEFAULT false,
    priority INTEGER NOT NULL DEFAULT 0,
    selection_weight DOUBLE PRECISION NOT NULL DEFAULT 1 CHECK (selection_weight >= 0),
    enabled BOOLEAN NOT NULL DEFAULT true,
    camera_perspective TEXT NOT NULL DEFAULT '',
    session_info TEXT NOT NULL DEFAULT '',
    commentary_context TEXT NOT NULL DEFAULT '',
    uploaded_by INTEGER REFERENCES racingcoach."Users"(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (clip_end_seconds IS NULL OR clip_end_seconds > clip_start_seconds)
  )`,
  'CREATE INDEX IF NOT EXISTS broadcast_videos_category_idx ON racingcoach."BroadcastVideos" (category, enabled, status)',
  'CREATE INDEX IF NOT EXISTS broadcast_videos_processing_idx ON racingcoach."BroadcastVideos" (updated_at) WHERE status IN (\'processing\', \'transcoding\')',
  // Each clip the Director picked and what became of it, for the Admin page and to avoid repeats
  `CREATE TABLE IF NOT EXISTS racingcoach."BroadcastVideoHistory" (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_key TEXT NOT NULL,
    video_id INTEGER REFERENCES racingcoach."BroadcastVideos"(id) ON DELETE SET NULL,
    category TEXT NOT NULL,
    title TEXT NOT NULL,
    trigger TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'selected',
    introduction_text TEXT,
    failure_reason TEXT,
    selected_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    started_at TIMESTAMPTZ,
    ended_at TIMESTAMPTZ
  )`,
  'CREATE INDEX IF NOT EXISTS broadcast_video_history_selected_at_idx ON racingcoach."BroadcastVideoHistory" (selected_at DESC)',
  'CREATE INDEX IF NOT EXISTS broadcast_video_history_session_idx ON racingcoach."BroadcastVideoHistory" (session_key, selected_at DESC)',
  // The timeline: each state the Director went through, by session and number, so it can pick up after a restart.
  // Kept 30 days (purgeDirectorLog)
  `CREATE TABLE IF NOT EXISTS racingcoach."BroadcastDirectorEvents" (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_key TEXT NOT NULL,
    seq INTEGER NOT NULL,
    event_id UUID NOT NULL UNIQUE,
    phase TEXT NOT NULL,
    source TEXT NOT NULL,
    video_id INTEGER,
    category TEXT,
    transition_at TIMESTAMPTZ,
    return_at TIMESTAMPTZ,
    live_at TIMESTAMPTZ,
    state JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (session_key, seq)
  )`,
  'CREATE INDEX IF NOT EXISTS broadcast_director_events_created_at_idx ON racingcoach."BroadcastDirectorEvents" (created_at)',
  // The Admin page's Engine Sounds (src/lib/engineAudioAssets.ts): not tied to a user and shared by everyone, the files
  // in the same object storage
  `CREATE TABLE IF NOT EXISTS racingcoach."EngineAudioAssets" (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    storage_key TEXT NOT NULL UNIQUE,
    content_type TEXT NOT NULL,
    size_bytes BIGINT NOT NULL,
    uploaded_by INTEGER REFERENCES racingcoach."Users"(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
  )`,
];
