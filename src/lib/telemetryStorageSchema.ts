// Lap telemetry in object storage: what it adds to the database (docs/telemetry-storage.md). Run by ensureUserSchema
// (users.ts) once "CollectorLaps" and the lap retention schema exist, inside its transaction. Additions only, and every
// statement can run again: existing rows read as inline Postgres laps, which they are.
//
// - "CollectorLaps" says where each lap's CSV is (storage_provider) and, for an object, its bucket, key, stored size,
//   SHA-256, content type and compression. csv_gzip becomes nullable, and a check keeps every row readable: a
//   postgres row always has csv_gzip, an object row always a key. Rolling a migrated row back is setting its
//   storage_provider to postgres while csv_gzip is still there (the key stays, so its object isn't deleted).
// - "TelemetryObjectCleanup" is the queue of objects to delete. Two triggers fill it in the same statement as the row
//   change, whatever made it (the retention job, an erasure, Delete Account's cascade, an erasure re-applied after a
//   restore, a re-upload with track positions moving the row to a new key, or SQL by hand), so a row is never gone
//   while nothing remembers its object. Uploads add a 'pending' entry before writing an object and remove it in the
//   transaction that inserts the row, so an upload that fails or dies half way leaves an entry, not an orphan.
//   The cleanup worker deletes an entry's object only when no lap row references its key.
import { PENDING_UPLOAD_GRACE_MS } from './telemetryStorageRules.ts';

export const TELEMETRY_CLEANUP_REASONS = ['pending', 'deleted', 'replaced', 'orphan'] as const;
export type TelemetryCleanupReason = (typeof TELEMETRY_CLEANUP_REASONS)[number];

export const PENDING_GRACE_SQL = `make_interval(secs => ${PENDING_UPLOAD_GRACE_MS / 1000})`;

export const TELEMETRY_STORAGE_SCHEMA: string[] = [
  `ALTER TABLE racingcoach."CollectorLaps" ADD COLUMN IF NOT EXISTS storage_provider TEXT NOT NULL DEFAULT 'postgres'`,
  `ALTER TABLE racingcoach."CollectorLaps" ADD COLUMN IF NOT EXISTS storage_status TEXT NOT NULL DEFAULT 'inline'`,
  `ALTER TABLE racingcoach."CollectorLaps" ADD COLUMN IF NOT EXISTS storage_bucket TEXT`,
  `ALTER TABLE racingcoach."CollectorLaps" ADD COLUMN IF NOT EXISTS storage_key TEXT`,
  // Size of the stored (compressed) object; csv_bytes stays the CSV's uncompressed, original size
  `ALTER TABLE racingcoach."CollectorLaps" ADD COLUMN IF NOT EXISTS stored_bytes INTEGER`,
  // SHA-256 (hex) of the compressed bytes, for the object and for csv_gzip alike
  `ALTER TABLE racingcoach."CollectorLaps" ADD COLUMN IF NOT EXISTS checksum_sha256 TEXT`,
  `ALTER TABLE racingcoach."CollectorLaps" ADD COLUMN IF NOT EXISTS content_type TEXT`,
  `ALTER TABLE racingcoach."CollectorLaps" ADD COLUMN IF NOT EXISTS compression TEXT`,
  // When the object was written and its size checked, and when it was last downloaded and its checksum matched
  `ALTER TABLE racingcoach."CollectorLaps" ADD COLUMN IF NOT EXISTS stored_at TIMESTAMPTZ`,
  `ALTER TABLE racingcoach."CollectorLaps" ADD COLUMN IF NOT EXISTS verified_at TIMESTAMPTZ`,
  // The backfill's failures for this row (telemetryMigration.ts), so a stuck row is visible and retried with backoff
  `ALTER TABLE racingcoach."CollectorLaps" ADD COLUMN IF NOT EXISTS migration_attempts INTEGER NOT NULL DEFAULT 0`,
  `ALTER TABLE racingcoach."CollectorLaps" ADD COLUMN IF NOT EXISTS migration_error TEXT`,
  `ALTER TABLE racingcoach."CollectorLaps" ADD COLUMN IF NOT EXISTS migration_next_attempt_at TIMESTAMPTZ`,
  `ALTER TABLE racingcoach."CollectorLaps" ALTER COLUMN csv_gzip DROP NOT NULL`,
  `DO $$ BEGIN
     IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'collector_laps_storage_check'
                    AND conrelid = 'racingcoach."CollectorLaps"'::regclass) THEN
       ALTER TABLE racingcoach."CollectorLaps" ADD CONSTRAINT collector_laps_storage_check CHECK (
         (storage_provider = 'postgres' AND csv_gzip IS NOT NULL)
         OR (storage_provider <> 'postgres' AND storage_key IS NOT NULL AND storage_bucket IS NOT NULL));
     END IF;
   END $$`,
  `CREATE INDEX IF NOT EXISTS collector_laps_storage_key_idx ON racingcoach."CollectorLaps" (storage_bucket, storage_key)
   WHERE storage_key IS NOT NULL`,
  `CREATE INDEX IF NOT EXISTS collector_laps_storage_provider_idx ON racingcoach."CollectorLaps" (storage_provider, id)`,

  // No foreign key to "Users": an account's objects are still deleted after the account is gone. user_id is the
  // internal ID only, for the Admin page and logs.
  `CREATE TABLE IF NOT EXISTS racingcoach."TelemetryObjectCleanup" (
     id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
     storage_provider TEXT NOT NULL,
     storage_bucket TEXT NOT NULL,
     storage_key TEXT NOT NULL,
     user_id INTEGER,
     reason TEXT NOT NULL CHECK (reason IN ('pending', 'deleted', 'replaced', 'orphan')),
     not_before TIMESTAMPTZ NOT NULL DEFAULT now(),
     attempts INTEGER NOT NULL DEFAULT 0,
     last_error TEXT,
     created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
     UNIQUE (storage_bucket, storage_key)
   )`,
  `CREATE INDEX IF NOT EXISTS telemetry_object_cleanup_not_before_idx ON racingcoach."TelemetryObjectCleanup" (not_before)`,

  `CREATE OR REPLACE FUNCTION racingcoach.queue_lap_object_cleanup() RETURNS trigger LANGUAGE plpgsql AS $$
   BEGIN
     INSERT INTO racingcoach."TelemetryObjectCleanup" (storage_provider, storage_bucket, storage_key, user_id, reason)
     VALUES (OLD.storage_provider, OLD.storage_bucket, OLD.storage_key, OLD.user_id,
             CASE WHEN TG_OP = 'DELETE' THEN 'deleted' ELSE 'replaced' END)
     ON CONFLICT (storage_bucket, storage_key) DO UPDATE
       SET reason = EXCLUDED.reason, not_before = LEAST(racingcoach."TelemetryObjectCleanup".not_before, now());
     RETURN NULL;
   END $$`,
  `DROP TRIGGER IF EXISTS collector_laps_object_deleted ON racingcoach."CollectorLaps"`,
  `CREATE TRIGGER collector_laps_object_deleted AFTER DELETE ON racingcoach."CollectorLaps"
   FOR EACH ROW WHEN (OLD.storage_key IS NOT NULL)
   EXECUTE FUNCTION racingcoach.queue_lap_object_cleanup()`,
  `DROP TRIGGER IF EXISTS collector_laps_object_replaced ON racingcoach."CollectorLaps"`,
  `CREATE TRIGGER collector_laps_object_replaced AFTER UPDATE OF storage_key, storage_bucket ON racingcoach."CollectorLaps"
   FOR EACH ROW WHEN (OLD.storage_key IS NOT NULL
     AND (OLD.storage_key IS DISTINCT FROM NEW.storage_key OR OLD.storage_bucket IS DISTINCT FROM NEW.storage_bucket))
   EXECUTE FUNCTION racingcoach.queue_lap_object_cleanup()`,

  // Daily counts for the Admin page (telemetryStorageMetrics.ts): puts, gets, misses, deletes, failures, cache hits
  `CREATE TABLE IF NOT EXISTS racingcoach."TelemetryStorageCounters" (
     day DATE NOT NULL,
     metric TEXT NOT NULL,
     count BIGINT NOT NULL DEFAULT 0,
     bytes BIGINT NOT NULL DEFAULT 0,
     PRIMARY KEY (day, metric)
   )`,
  // One row per backfill, verification, cleanup, reconciliation or legacy purge run; counts and messages, no telemetry
  `CREATE TABLE IF NOT EXISTS racingcoach."TelemetryStorageRuns" (
     id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
     kind TEXT NOT NULL CHECK (kind IN ('backfill', 'verify', 'cleanup', 'reconcile', 'purgeLegacy')),
     started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
     finished_at TIMESTAMPTZ,
     started_by INTEGER,
     processed INTEGER NOT NULL DEFAULT 0,
     succeeded INTEGER NOT NULL DEFAULT 0,
     failed INTEGER NOT NULL DEFAULT 0,
     bytes BIGINT NOT NULL DEFAULT 0,
     details JSONB,
     error TEXT
   )`,
  `CREATE INDEX IF NOT EXISTS telemetry_storage_runs_kind_started_idx ON racingcoach."TelemetryStorageRuns" (kind, started_at)`,
];
