// The tables behind data subject rights (privacyRules.ts has the rules, privacyRequests.ts the queries). Additive only:
// new tables and one new "Sessions" column, nothing existing altered, so it's safe to deploy and to roll back (the old
// code ignores them). Run by ensureUserSchema (users.ts) inside its transaction, after "Users" exists; every statement
// can run again.
import { REQUEST_STATUSES, REQUEST_TYPES } from './privacyRules.ts';

const list = (values: readonly string[]) => values.map((value) => `'${value}'`).join(', ');

export const PRIVACY_SCHEMA: string[] = [
  // One row per request. user_id is the account it's about (SET NULL when the account is deleted, its ID kept in
  // deleted_user_id); a request from someone without an account has only requester_name and requester_email, the
  // address it was verified by and is answered at. submitted_at is receipt, which starts the one-month deadline
  // (due_at). resolution is what the requester is told; legal_justification and retained are the Admin's record of
  // why something was refused or kept. purge_after is 3 years after it closed.
  `CREATE TABLE IF NOT EXISTS racingcoach."PrivacyRequests" (
     id UUID PRIMARY KEY,
     user_id INTEGER REFERENCES racingcoach."Users"(id) ON DELETE SET NULL,
     deleted_user_id INTEGER,
     requester_name TEXT,
     requester_email TEXT,
     request_type TEXT NOT NULL CHECK (request_type IN (${list(REQUEST_TYPES)})),
     details TEXT NOT NULL DEFAULT '',
     scope JSONB NOT NULL DEFAULT '{}'::jsonb,
     status TEXT NOT NULL CHECK (status IN (${list(REQUEST_STATUSES)})),
     verification_status TEXT NOT NULL CHECK (verification_status IN ('unverified', 'verified', 'failed')),
     verification_method TEXT CHECK (verification_method IN ('session', 'reauth', 'email', 'manual')),
     verified_at TIMESTAMPTZ,
     submitted_at TIMESTAMPTZ NOT NULL DEFAULT now(),
     due_at TIMESTAMPTZ NOT NULL,
     extended_due_at TIMESTAMPTZ,
     extension_reason TEXT,
     completed_at TIMESTAMPTZ,
     closed_by INTEGER,
     resolution TEXT,
     legal_justification TEXT,
     retained JSONB NOT NULL DEFAULT '[]'::jsonb,
     updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
     purge_after TIMESTAMPTZ
   )`,
  `CREATE INDEX IF NOT EXISTS privacy_requests_user_idx ON racingcoach."PrivacyRequests" (user_id, submitted_at)`,
  `CREATE INDEX IF NOT EXISTS privacy_requests_status_idx ON racingcoach."PrivacyRequests" (status, due_at)`,
  `CREATE INDEX IF NOT EXISTS privacy_requests_email_idx ON racingcoach."PrivacyRequests" (lower(requester_email))`,
  // The audit history: every status change, verification, note, communication and job outcome. actor_id is the
  // Admin's account ID, with no foreign key so the history stays whole. visible_to_requester marks what Privacy Request
  // History shows the requester (their own actions, status changes and messages to them; never internal notes).
  `CREATE TABLE IF NOT EXISTS racingcoach."PrivacyRequestEvents" (
     id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
     request_id UUID NOT NULL REFERENCES racingcoach."PrivacyRequests"(id) ON DELETE CASCADE,
     at TIMESTAMPTZ NOT NULL DEFAULT now(),
     actor TEXT NOT NULL CHECK (actor IN ('requester', 'admin', 'system')),
     actor_id INTEGER,
     event TEXT NOT NULL,
     from_status TEXT,
     to_status TEXT,
     note TEXT,
     visible_to_requester BOOLEAN NOT NULL DEFAULT false
   )`,
  `CREATE INDEX IF NOT EXISTS privacy_request_events_request_idx ON racingcoach."PrivacyRequestEvents" (request_id, at)`,
  // Background work (privacyJobs.ts): an export, an erasure, or deleting stored files left behind. Claimed with
  // FOR UPDATE SKIP LOCKED, retried with backoff until max_attempts, then left failed for an Admin. One export per
  // request, so submitting twice can't make two; erasures can run again (an Admin approving reviewed categories), as
  // each one is idempotent.
  `CREATE TABLE IF NOT EXISTS racingcoach."PrivacyJobs" (
     id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
     request_id UUID REFERENCES racingcoach."PrivacyRequests"(id) ON DELETE CASCADE,
     kind TEXT NOT NULL CHECK (kind IN ('export', 'erasure', 'purgeObjects')),
     status TEXT NOT NULL CHECK (status IN ('queued', 'running', 'succeeded', 'failed')) DEFAULT 'queued',
     attempts INTEGER NOT NULL DEFAULT 0,
     max_attempts INTEGER NOT NULL DEFAULT 5,
     run_after TIMESTAMPTZ NOT NULL DEFAULT now(),
     locked_until TIMESTAMPTZ,
     payload JSONB NOT NULL DEFAULT '{}'::jsonb,
     result JSONB,
     last_error TEXT,
     created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
     started_at TIMESTAMPTZ,
     finished_at TIMESTAMPTZ
   )`,
  `CREATE UNIQUE INDEX IF NOT EXISTS privacy_jobs_request_export_key ON racingcoach."PrivacyJobs" (request_id, kind)
   WHERE kind = 'export'`,
  `CREATE INDEX IF NOT EXISTS privacy_jobs_queue_idx ON racingcoach."PrivacyJobs" (status, run_after)`,
  // Generated exports: a ZIP in object storage (object_key) or, without it, here (content). Downloadable by their
  // owner only, until expires_at; then the job sweep deletes the file and sets deleted_at.
  `CREATE TABLE IF NOT EXISTS racingcoach."PrivacyExports" (
     id UUID PRIMARY KEY,
     request_id UUID NOT NULL REFERENCES racingcoach."PrivacyRequests"(id) ON DELETE CASCADE,
     user_id INTEGER NOT NULL REFERENCES racingcoach."Users"(id) ON DELETE CASCADE,
     kind TEXT NOT NULL CHECK (kind IN ('access', 'portability')),
     created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
     expires_at TIMESTAMPTZ NOT NULL,
     storage TEXT NOT NULL CHECK (storage IN ('object', 'database')),
     object_key TEXT,
     content BYTEA,
     size_bytes BIGINT NOT NULL,
     sha256 TEXT NOT NULL,
     downloads INTEGER NOT NULL DEFAULT 0,
     last_downloaded_at TIMESTAMPTZ,
     deleted_at TIMESTAMPTZ
   )`,
  `CREATE INDEX IF NOT EXISTS privacy_exports_user_idx ON racingcoach."PrivacyExports" (user_id, created_at)`,
  `CREATE INDEX IF NOT EXISTS privacy_exports_expires_idx ON racingcoach."PrivacyExports" (expires_at) WHERE deleted_at IS NULL`,
  // Email verification of a request from someone who isn't signed in: a hashed one-time link, 24 hours
  `CREATE TABLE IF NOT EXISTS racingcoach."PrivacyVerifications" (
     token_hash TEXT PRIMARY KEY,
     request_id UUID NOT NULL REFERENCES racingcoach."PrivacyRequests"(id) ON DELETE CASCADE,
     expires_at TIMESTAMPTZ NOT NULL,
     used_at TIMESTAMPTZ
   )`,
  // Step-up sign-in for accounts without a password (Google sign-in): a hashed 6-digit code emailed to the account,
  // 15 minutes, 5 tries (reauth.ts). Accounts with a password re-enter it instead.
  `CREATE TABLE IF NOT EXISTS racingcoach."PrivacyReauthCodes" (
     user_id INTEGER PRIMARY KEY REFERENCES racingcoach."Users"(id) ON DELETE CASCADE,
     code_hash TEXT NOT NULL,
     expires_at TIMESTAMPTZ NOT NULL,
     attempts INTEGER NOT NULL DEFAULT 0
   )`,
  // When this sign-in session last proved it's the account holder (reauth.ts); NULL until it does. Milliseconds, like
  // expires_at
  `ALTER TABLE racingcoach."Sessions" ADD COLUMN IF NOT EXISTS reauthenticated_at BIGINT`,
  // The erasure ledger (dataErasure.ts): one row per account deleted or category erased, with no personal data beyond
  // the account's internal ID and creation time (which together can't match a later account that reuses the ID).
  // Mirrored to object storage, which database backups don't roll back, so erasures are applied again to a restored
  // database before it's used (reapplyErasures). category is 'account' or an ERASABLE_CATEGORIES name; rows in it
  // from before erased_at are what was erased.
  `CREATE TABLE IF NOT EXISTS racingcoach."ErasureLedger" (
     id UUID PRIMARY KEY,
     user_id INTEGER NOT NULL,
     account_created_at TIMESTAMPTZ NOT NULL,
     category TEXT NOT NULL,
     erased_at TIMESTAMPTZ NOT NULL DEFAULT now(),
     request_id UUID,
     mirrored_at TIMESTAMPTZ
   )`,
  `CREATE INDEX IF NOT EXISTS erasure_ledger_user_idx ON racingcoach."ErasureLedger" (user_id, account_created_at)`,
];
