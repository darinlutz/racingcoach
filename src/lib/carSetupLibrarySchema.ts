// The iRacing Setups library's tables (docs/setups.md's iRacing setup collection), run by ensureUserSchema (users.ts)
// after "Cars", "Users" and "TelemetryObjectCleanup" exist. Additive only: new tables, indexes, a function and its
// triggers, so it's safe on the live database. Not tied to a user's own data: the setups are shared reference files an
// Admin imported, so the importing account is set NULL when it's deleted (like Expert Laps' uploaded_by).
export const CAR_SETUP_LIBRARY_SCHEMA = [
  // One setup: its .sto (always) and the .htm iRacing exported beside it (when there was one), both in the telemetry
  // bucket (storage_provider r2) or, in local development only, a folder on the computer (disk). A row exists only
  // once its objects were stored and checked, so there's never a catalog entry without its files. htm_parsed is
  // setupHtm.ts's result (values with their original labels, units and box, warnings), NULL without an .htm
  `CREATE TABLE IF NOT EXISTS racingcoach."CarSetups" (
     id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
     simulator TEXT NOT NULL DEFAULT 'iracing',
     car_folder TEXT NOT NULL,
     setup_path TEXT NOT NULL,
     setup_name TEXT NOT NULL,
     car_id INTEGER REFERENCES racingcoach."Cars"(id) ON DELETE SET NULL,
     car_name TEXT,
     setup_source TEXT NOT NULL DEFAULT 'localGarage',
     provenance TEXT NOT NULL DEFAULT 'unknown',
     storage_provider TEXT NOT NULL,
     storage_bucket TEXT NOT NULL,
     sto_file_name TEXT NOT NULL,
     sto_key TEXT NOT NULL,
     sto_sha256 TEXT NOT NULL,
     sto_bytes INTEGER NOT NULL,
     sto_info JSONB,
     htm_file_name TEXT,
     htm_key TEXT,
     htm_sha256 TEXT,
     htm_bytes INTEGER,
     htm_parse_status TEXT NOT NULL DEFAULT 'missing',
     htm_parsed JSONB,
     version INTEGER NOT NULL DEFAULT 1,
     import_status TEXT NOT NULL DEFAULT 'complete',
     imported_by_user_id INTEGER REFERENCES racingcoach."Users"(id) ON DELETE SET NULL,
     last_import_id INTEGER,
     imported_at TIMESTAMPTZ NOT NULL DEFAULT now(),
     updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
     last_seen_at TIMESTAMPTZ NOT NULL DEFAULT now(),
     CONSTRAINT car_setups_simulator_check CHECK (simulator IN ('iracing')),
     CONSTRAINT car_setups_source_check CHECK (setup_source IN ('localGarage')),
     CONSTRAINT car_setups_provenance_check CHECK (provenance IN ('official', 'user', 'unknown')),
     CONSTRAINT car_setups_htm_status_check CHECK (htm_parse_status IN ('parsed', 'empty', 'failed', 'missing')),
     CONSTRAINT car_setups_import_status_check CHECK (import_status IN ('complete', 'completeWithWarnings')),
     CONSTRAINT car_setups_htm_check CHECK ((htm_key IS NULL) = (htm_sha256 IS NULL) AND (htm_key IS NULL) = (htm_file_name IS NULL))
   )`,
  `CREATE UNIQUE INDEX IF NOT EXISTS car_setups_identity ON racingcoach."CarSetups" (simulator, lower(car_folder), lower(setup_path))`,
  `CREATE INDEX IF NOT EXISTS car_setups_car ON racingcoach."CarSetups" (car_id, lower(setup_path))`,
  // Each press of the collector's Get Car Setups: what it found, what each setup became and what failed
  `CREATE TABLE IF NOT EXISTS racingcoach."CarSetupImports" (
     id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
     started_by_user_id INTEGER REFERENCES racingcoach."Users"(id) ON DELETE SET NULL,
     simulator TEXT NOT NULL DEFAULT 'iracing',
     collector_version TEXT,
     status TEXT NOT NULL DEFAULT 'running',
     car_folders TEXT[] NOT NULL DEFAULT '{}',
     setups_found INTEGER NOT NULL DEFAULT 0,
     sto_files INTEGER NOT NULL DEFAULT 0,
     htm_files INTEGER NOT NULL DEFAULT 0,
     new_count INTEGER NOT NULL DEFAULT 0,
     changed_count INTEGER NOT NULL DEFAULT 0,
     unchanged_count INTEGER NOT NULL DEFAULT 0,
     failed_count INTEGER NOT NULL DEFAULT 0,
     unresolved JSONB NOT NULL DEFAULT '[]',
     errors JSONB NOT NULL DEFAULT '[]',
     started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
     finished_at TIMESTAMPTZ,
     CONSTRAINT car_setup_imports_status_check CHECK (status IN ('running', 'complete', 'completeWithErrors', 'failed'))
   )`,
  `CREATE INDEX IF NOT EXISTS car_setup_imports_started ON racingcoach."CarSetupImports" (started_at DESC)`,
  // A setup's object no longer referenced (the row deleted, or its file replaced by a changed one) is queued for the
  // telemetry cleanup worker (telemetryCleanup.ts), which deletes it only when no setup references the key any more
  // (identical files share one object). Only R2 objects: the local development folder is left alone
  `CREATE OR REPLACE FUNCTION racingcoach.queue_car_setup_object_cleanup() RETURNS trigger LANGUAGE plpgsql AS $$
   BEGIN
     IF OLD.storage_provider <> 'r2' THEN RETURN NULL; END IF;
     IF TG_OP = 'DELETE' OR NEW.sto_key IS DISTINCT FROM OLD.sto_key THEN
       INSERT INTO racingcoach."TelemetryObjectCleanup" (storage_provider, storage_bucket, storage_key, reason)
       VALUES (OLD.storage_provider, OLD.storage_bucket, OLD.sto_key, CASE WHEN TG_OP = 'DELETE' THEN 'deleted' ELSE 'replaced' END)
       ON CONFLICT (storage_bucket, storage_key) DO NOTHING;
     END IF;
     IF OLD.htm_key IS NOT NULL AND (TG_OP = 'DELETE' OR NEW.htm_key IS DISTINCT FROM OLD.htm_key) THEN
       INSERT INTO racingcoach."TelemetryObjectCleanup" (storage_provider, storage_bucket, storage_key, reason)
       VALUES (OLD.storage_provider, OLD.storage_bucket, OLD.htm_key, CASE WHEN TG_OP = 'DELETE' THEN 'deleted' ELSE 'replaced' END)
       ON CONFLICT (storage_bucket, storage_key) DO NOTHING;
     END IF;
     RETURN NULL;
   END $$`,
  `DROP TRIGGER IF EXISTS car_setups_object_deleted ON racingcoach."CarSetups"`,
  `CREATE TRIGGER car_setups_object_deleted AFTER DELETE ON racingcoach."CarSetups"
     FOR EACH ROW EXECUTE FUNCTION racingcoach.queue_car_setup_object_cleanup()`,
  `DROP TRIGGER IF EXISTS car_setups_object_replaced ON racingcoach."CarSetups"`,
  `CREATE TRIGGER car_setups_object_replaced AFTER UPDATE OF sto_key, htm_key ON racingcoach."CarSetups"
     FOR EACH ROW EXECUTE FUNCTION racingcoach.queue_car_setup_object_cleanup()`,
];

export const CAR_SETUP_LIBRARY_TABLES = ['CarSetups', 'CarSetupImports'];
