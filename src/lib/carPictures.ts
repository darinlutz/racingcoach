// Session info writes a CarPath's folders with spaces ("dirtsprint winged 410"), the support page with backslashes
const pathKey = (carPath: string) => carPath.trim().toLowerCase().split(/[\\/\s]+/).filter(Boolean).join(' ');

const PICTURE_BY_PATH = new Map(IRACING_CARS.map(([carPath, picture]) => [pathKey(carPath), picture]));
// A name's own picture wins over another car's name, so a Car Data name that is a picture's never moves
const PICTURE_BY_NAME = new Map(
  IRACING_CARS.flatMap(([, picture, ...names]) => names.map((name) => [slug(name).replace(/^legacy-/, ''), picture] as const))
);

// The picture of a car by iRacing's CarPath (a lap's carKey) when known, else its name, or null for a car without
// one (e.g. one a user added)
export function carPictureUrl(name: string, carPath?: string | null): string | null {
  const byPath = carPath ? PICTURE_BY_PATH.get(pathKey(carPath)) : undefined;
  const key = slug(name);
  const picture = byPath ?? (CAR_PICTURES.has(key) ? key : PICTURE_BY_NAME.get(key.replace(/^legacy-/, '')));
  return picture && CAR_PICTURES.has(picture) ? `/assets/carPics/${picture}.jpg` : null;
}
