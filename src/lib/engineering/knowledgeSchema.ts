import { query } from '@/lib/db';

// The Race Engineering knowledge base's tables, in the racingcoach schema. Only adds (CREATE ... IF NOT EXISTS), so it
// is safe to run on every server start and on the live database; nothing existing is touched. Run lazily by
// knowledgeStore.ts the first time the knowledge base is read or written, not by ensureUserSchema, so a problem
// here can never stop the rest of the site. No personal data: the tables hold engineering content, never user IDs
// (personalDataInventory.ts lists them in NON_PERSONAL_TABLES).
//
// Embeddings are stored as real[] (with the model that made them) and compared in the server's memory: the corpus is
// a few hundred to a few thousand chunks, cached for 5 minutes, which is faster than a round trip to the database.
// pgvector would only pay off past tens of thousands of chunks; docs/race-engineering-rag.md has the migration.
export const ENGINEERING_SCHEMA = [
  `CREATE TABLE IF NOT EXISTS racingcoach."EngineeringSources" (
     id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
     key TEXT NOT NULL UNIQUE,
     title TEXT NOT NULL,
     url TEXT,
     kind TEXT NOT NULL,
     license TEXT NOT NULL,
     publisher TEXT,
     created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
     updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
   )`,
  // One row per version of a document; at most one active version per document_key
  `CREATE TABLE IF NOT EXISTS racingcoach."EngineeringDocuments" (
     id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
     document_key TEXT NOT NULL,
     version INTEGER NOT NULL,
     title TEXT NOT NULL,
     source_key TEXT NOT NULL REFERENCES racingcoach."EngineeringSources"(key) ON UPDATE CASCADE,
     format TEXT NOT NULL,
     authority TEXT NOT NULL,
     verification TEXT NOT NULL,
     simulators TEXT[] NOT NULL DEFAULT '{any}',
     car_classes TEXT[] NOT NULL DEFAULT '{any}',
     cars TEXT[] NOT NULL DEFAULT '{}',
     components TEXT[] NOT NULL DEFAULT '{}',
     phases TEXT[] NOT NULL DEFAULT '{}',
     symptoms TEXT[] NOT NULL DEFAULT '{}',
     content TEXT NOT NULL,
     record JSONB,
     content_hash TEXT NOT NULL,
     status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'superseded', 'inactive')),
     status_reason TEXT,
     reviewed_at TIMESTAMPTZ,
     created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
     updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
     UNIQUE (document_key, version)
   )`,
  `CREATE UNIQUE INDEX IF NOT EXISTS engineering_documents_one_active
     ON racingcoach."EngineeringDocuments" (document_key) WHERE status = 'active'`,
  `CREATE INDEX IF NOT EXISTS engineering_documents_hash ON racingcoach."EngineeringDocuments" (content_hash)`,
  `CREATE TABLE IF NOT EXISTS racingcoach."EngineeringChunks" (
     id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
     document_id INTEGER NOT NULL REFERENCES racingcoach."EngineeringDocuments"(id) ON DELETE CASCADE,
     chunk_index INTEGER NOT NULL,
     title TEXT NOT NULL,
     text TEXT NOT NULL,
     token_estimate INTEGER NOT NULL,
     content_hash TEXT NOT NULL,
     embedding REAL[],
     embedding_model TEXT,
     embedded_at TIMESTAMPTZ,
     tsv TSVECTOR GENERATED ALWAYS AS (to_tsvector('simple', title || ' ' || text)) STORED,
     UNIQUE (document_id, chunk_index)
   )`,
  `CREATE INDEX IF NOT EXISTS engineering_chunks_tsv ON racingcoach."EngineeringChunks" USING GIN (tsv)`,
  // Ingestion runs (a whole corpus, one upload, a reindex or an embedding pass), with what went wrong
  `CREATE TABLE IF NOT EXISTS racingcoach."EngineeringIngestionJobs" (
     id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
     kind TEXT NOT NULL,
     status TEXT NOT NULL DEFAULT 'running' CHECK (status IN ('running', 'succeeded', 'failed', 'partial')),
     detail JSONB NOT NULL DEFAULT '{}',
     error TEXT,
     attempts INTEGER NOT NULL DEFAULT 1,
     started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
     finished_at TIMESTAMPTZ
   )`,
  // Per-car setup capabilities a person has checked in the car's garage, overriding the class defaults in
  // setupCapabilities.ts. range only when checked; never guessed.
  `CREATE TABLE IF NOT EXISTS racingcoach."EngineeringSetupCapabilities" (
     id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
     simulator TEXT NOT NULL,
     car TEXT NOT NULL,
     parameter TEXT NOT NULL,
     in_car BOOLEAN NOT NULL,
     garage BOOLEAN NOT NULL,
     verification TEXT NOT NULL DEFAULT 'verified',
     note TEXT,
     range JSONB,
     updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
     UNIQUE (simulator, car, parameter)
   )`,
  // Optional worked examples: a symptom, what the telemetry showed and what fixed it
  `CREATE TABLE IF NOT EXISTS racingcoach."EngineeringCaseStudies" (
     id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
     title TEXT NOT NULL,
     simulator TEXT NOT NULL,
     car TEXT,
     track TEXT,
     symptom TEXT NOT NULL,
     phase TEXT,
     evidence JSONB NOT NULL DEFAULT '{}',
     outcome TEXT NOT NULL,
     verification TEXT NOT NULL DEFAULT 'unverified',
     created_at TIMESTAMPTZ NOT NULL DEFAULT now()
   )`,
];

export const ENGINEERING_TABLES = [
  'EngineeringSources',
  'EngineeringDocuments',
  'EngineeringChunks',
  'EngineeringIngestionJobs',
  'EngineeringSetupCapabilities',
  'EngineeringCaseStudies',
];

const globalSchema = globalThis as typeof globalThis & { engineeringSchema?: Promise<void> };

export function ensureEngineeringSchema(): Promise<void> {
  if (!globalSchema.engineeringSchema) {
    globalSchema.engineeringSchema = (async () => {
      await query('CREATE SCHEMA IF NOT EXISTS racingcoach');
      for (const statement of ENGINEERING_SCHEMA) await query(statement);
    })().catch((error) => {
      globalSchema.engineeringSchema = undefined;
      throw error;
    });
  }
  return globalSchema.engineeringSchema;
}
