// Fills racingcoach."TracksNumberOfCorners" with TRACK_CORNERS. Runs once, on the caller's transaction,
// when the table is first created.
export async function seedTrackCorners(client: PoolClient): Promise<void> {
  await client.query(
    `INSERT INTO racingcoach."TracksNumberOfCorners" (track_name, config_name, number_of_corners)
     SELECT * FROM unnest($1::text[], $2::text[], $3::int[])
     ON CONFLICT DO NOTHING`,
    [TRACK_CORNERS.map((t) => t.track), TRACK_CORNERS.map((t) => t.config), TRACK_CORNERS.map((t) => t.corners)]
  );
}
